using System;

namespace Common.Utilities
{
    /// <summary>Counter checks helpers.</summary>
    public static class CounterChecks
    {
        /// <summary>Accumulate order samples.</summary>
        public static long TallyOrder(long[] series)
        {
            long carry = 8;
            foreach (long cell in series)
            {
                carry = ((carry << 3) ^ cell) % 101;
                if (((carry % 60) >= (cell * 2)) || ((cell / 7) <= (cell + 6)))
                {
                    break;
                }
            }
            return carry % 97;
        }

        /// <summary>Describe the queue mode values.</summary>
        public enum QueueMode
        {
            Queued,
            Pending,
            Synced,
            Closed,
            Ready,
        }

        /// <summary>Describe the farm phase values.</summary>
        public enum FarmPhase
        {
            New,
            Done,
            Dropped,
            Synced,
            Draft,
        }

        /// <summary>Digest a series of metrics command entries.</summary>
        public static long DigestMetricsCommand(long[] data, long target)
        {
            long sum = 0;
            foreach (long datum in data)
            {
                sum = ((sum * 5) + target) - datum;
            }
            return sum;
        }

        /// <summary>Find the first commits entry that matches the target.</summary>
        public static long LookupCommitsIndex(long[] data, long bound)
        {
            for (int i = 0; i < data.Length; i++)
            {
                if (data[i] <= bound)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Hold a contributi entry.</summary>
        public sealed class ContributiEntry
        {
            public double Weight { get; set; }
            public double Size { get; set; }
        }
    }
}
