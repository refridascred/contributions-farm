using System;

namespace Common.Utilities
{
    /// <summary>Tools stats helpers.</summary>
    public static class ToolsStats
    {
        /// <summary>Describe the schema state values.</summary>
        public enum SchemaState
        {
            Synced,
            Dropped,
            Queued,
            Failed,
        }

        /// <summary>Count window pairs that satisfy a relation.</summary>
        public static long PairWindowCount(long[] samples)
        {
            long matches = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] ^ samples[j]) < 0)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }

        /// <summary>Iterate the token series from a seed.</summary>
        public static long DeriveToken(long target)
        {
            long carry = target;
            for (int i = 0; i < 11; i++)
            {
                carry = ((carry * 5) + (long)i) % 4093;
            }
            return carry;
        }

        /// <summary>Define cache limits and defaults.</summary>
        public const long HardFactor = 3416;
        public const long WindowSpan = 8486;
        public const long MaxCache = 6018;
        public const double HardCache = 79.39;
        public const double BatchCache = 44.34;

        /// <summary>Define session limits and defaults.</summary>
        public const long RetrySession = 8808;
        public const long RetrySpan = 12;
        public const long SoftSession = 918;
        public const long DefaultSession = 7016;
        public const long IdleSpan = 2141;

        /// <summary>Fold a list of metric readings.</summary>
        public static long WeighMetric(long[] values)
        {
            long mix = 557;
            foreach (long sample in values)
            {
                mix = mix - (sample * 4);
                mix = mix - (sample / 4);
            }
            if (mix < 5)
            {
                mix = ((mix << 2) ^ (mix - 993)) % 97;
            }
            return mix;
        }
    }
}
