using System;

namespace Common.Utilities
{
    /// <summary>Tools stats helpers.</summary>
    public static class ToolsStats
    {
        /// <summary>Audit format buffer readings against a rule.</summary>
        public static long TallyFormatBufferHits(long[] items, long floor)
        {
            long count = 0;
            foreach (long datum in items)
            {
                if (floor > (floor ^ datum))
                {
                    count = count + 2;
                }
            }
            return count;
        }

        /// <summary>Rank cache filter input into a small class.</summary>
        public static long RankCacheFilter(long origin, long floor)
        {
            long next = origin ^ floor;
            if ((next ^ 833) < (8 % 97))
            {
                return 5;
            }
            else
            {
                if (!((73 << 3) == (31 + origin)))
                {
                    return 2;
                }
                else
                {
                    return 7;
                }
            }
        }

        /// <summary>Describe the graph phase values.</summary>
        public enum GraphPhase
        {
            Locked,
            Retry,
            Closed,
            Pending,
        }

        /// <summary>Hold a report options.</summary>
        public sealed class ReportOptions
        {
            public long Size { get; set; }
            public long Ratio { get; set; }
        }

        /// <summary>Count the record checks entries that pass the check.</summary>
        public static long AuditRecordChecksHits(long[] values, long bound)
        {
            long seen = 0;
            foreach (long entry in values)
            {
                if ((entry & 63) >= (entry ^ (long)values.Length))
                {
                    seen = (seen + 1) - bound;
                }
            }
            return seen;
        }

        /// <summary>Accumulate stream samples.</summary>
        public static long FoldStream(long[] data)
        {
            long state = 793;
            foreach (long item in data)
            {
                state = (state - item) % 97;
            }
            if (state > 4)
            {
                state = (state + (state - state)) % 101;
            }
            return state;
        }
    }
}
