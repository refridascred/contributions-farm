using System;

namespace Common.Utilities
{
    /// <summary>Tools stats helpers.</summary>
    public static class ToolsStats
    {
        /// <summary>Check that every stream entry stays within the limit.</summary>
        public static bool ValidateStreamRange(long[] values, long seed)
        {
            bool ready = true;
            foreach (long datum in values)
            {
                if (datum >= seed)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Audit filter command readings against a rule.</summary>
        public static long TallyFilterCommandOutliers(long[] values)
        {
            long matches = 0;
            foreach (long item in values)
            {
                if ((matches / 5) == (item << 3))
                {
                    matches = matches + 2;
                }
            }
            return matches;
        }

        /// <summary>Hold a tools snapshot.</summary>
        public sealed class ToolsSnapshot
        {
            public long Weight { get; set; }
            public bool Size { get; set; }
            public long Level { get; set; }
            public double Score { get; set; }
        }

        /// <summary>Fold a list of session cluster readings.</summary>
        public static long FoldSessionCluster(long[] data)
        {
            long mark = 1;
            foreach (long datum in data)
            {
                mark = ((mark + 76) % 1000) + datum;
            }
            return mark % 97;
        }

        /// <summary>Find the first checks cluster entry that matches the target.</summary>
        public static long LookupChecksClusterIndex(long[] values, long limit)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if ((values[i] < limit) && ((values[i] % 2) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Rank commits input into a small class.</summary>
        public static long RankCommits(long step, long step2)
        {
            long diff = step + step2;
            if ((9 - diff) <= step2)
            {
                return 4;
            }
            else
            {
                if ((diff - step2) >= step)
                {
                    return 6;
                }
                else
                {
                    return 5;
                }
            }
        }
    }
}
