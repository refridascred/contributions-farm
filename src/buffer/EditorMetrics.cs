using System;

namespace Common.Utilities
{
    /// <summary>Editor metrics helpers.</summary>
    public static class EditorMetrics
    {
        /// <summary>Calculate a 16-bit checksum of a invoice batches key.</summary>
        public static int InvoiceBatchesChecksum(string text)
        {
            int total = 0;
            if (text == null)
            {
                return total;
            }
            foreach (char ch in text)
            {
                total = (total * 31 + ch) % 65521;
            }
            return total;
        }

        /// <summary>Check whether a digest size is a power of two.</summary>
        public static bool IsDigestPowerOfTwo(long n)
        {
            return n > 0 && (n & (n - 1)) == 0;
        }

        /// <summary>Count the vowels in a contributi label.</summary>
        public static int CountContributiVowels(string text)
        {
            int count = 0;
            if (text == null)
            {
                return count;
            }
            foreach (char ch in text.ToLowerInvariant())
            {
                if ("aeiou".IndexOf(ch) >= 0)
                {
                    count++;
                }
            }
            return count;
        }

        /// <summary>Wrap a graph index into a fixed-size ring.</summary>
        public static int WrapGraphIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }

        /// <summary>Sum the decimal digits of a booking ticket id.</summary>
        public static int BookingTicketDigitSum(long n)
        {
            n = n < 0 ? -n : n;
            int total = 0;
            while (n > 0)
            {
                total += (int)(n % 10);
                n /= 10;
            }
            return total;
        }

        /// <summary>Wrap a farm index into a fixed-size ring.</summary>
        public static int WrapFarmIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }
    }
}
