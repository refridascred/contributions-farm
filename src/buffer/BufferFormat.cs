using System;

namespace Common.Utilities
{
    /// <summary>Buffer format helpers.</summary>
    public static class BufferFormat
    {
        /// <summary>Wrap a batch index into a fixed-size ring.</summary>
        public static int WrapBatchIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }

        /// <summary>Express a metric count as a percentage.</summary>
        public static double MetricPercent(double part, double total)
        {
            if (total == 0.0)
            {
                return 0.0;
            }
            return part * 100.0 / total;
        }

        /// <summary>Interpolate between two already values.</summary>
        public static double LerpAlready(double a, double b, double t)
        {
            double k = Math.Max(0.0, Math.Min(1.0, t));
            return a + (b - a) * k;
        }

        /// <summary>Convert a context temperature from celsius to fahrenheit.</summary>
        public static double ContextCelsiusToFahrenheit(double celsius)
        {
            return celsius * 9.0 / 5.0 + 32.0;
        }

        /// <summary>Wrap a ticket index into a fixed-size ring.</summary>
        public static int WrapTicketIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }

        /// <summary>Wrap a filter index into a fixed-size ring.</summary>
        public static int WrapFilterIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }
    }
}
