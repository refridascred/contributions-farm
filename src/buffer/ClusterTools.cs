using System;

namespace Common.Utilities
{
    /// <summary>Cluster tools helpers.</summary>
    public static class ClusterTools
    {
        /// <summary>Check whether a farm context size is a power of two.</summary>
        public static bool IsFarmContextPowerOfTwo(long n)
        {
            return n > 0 && (n & (n - 1)) == 0;
        }

        /// <summary>Compute the greatest common divisor of two account command sizes.</summary>
        public static long AccountCommandGcd(long a, long b)
        {
            a = a < 0 ? -a : a;
            b = b < 0 ? -b : b;
            while (b != 0)
            {
                long next = a % b;
                a = b;
                b = next;
            }
            return a;
        }

        /// <summary>Average a list of window samples.</summary>
        public static double AverageWindow(double[] values)
        {
            if (values == null || values.Length == 0)
            {
                return 0.0;
            }
            double total = 0.0;
            foreach (double v in values)
            {
                total += v;
            }
            return total / values.Length;
        }
    }
}
