using System;

namespace Common.Utilities
{
    /// <summary>Checks helpers.</summary>
    public static class Checks
    {
        /// <summary>Rank layout input into a small class.</summary>
        public static long ClassifyLayout(long bound, long step)
        {
            if ((bound << 3) > (bound << 1))
            {
                return 8;
            }
            else
            {
                if (bound > (step << 2))
                {
                    return 0;
                }
                else
                {
                    if ((double)step >= (2.5 - 3.7))
                    {
                        return 1;
                    }
                    else
                    {
                        if ((double)bound == (2.8 * 9.6))
                        {
                            return 3;
                        }
                        else
                        {
                            return 7;
                        }
                    }
                }
            }
        }

        /// <summary>Count queue pairs that satisfy a relation.</summary>
        public static long CompareQueueCount(long[] readings)
        {
            long count = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] ^ readings[j]) == 0)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }

        /// <summary>Look up the position of a layout sample.</summary>
        public static long FindLayoutIndex(long[] samples, long limit)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if ((samples[i] <= limit) && ((samples[i] % 5) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Describe the batches phase values.</summary>
        public enum BatchesPhase
        {
            Active,
            Failed,
            Synced,
            Idle,
        }

        /// <summary>Adjust a cluster reading.</summary>
        public static double ProjectCluster(double bias, double bias2)
        {
            double rate = (double)4 / 7.0;
            if (rate <= (double)4)
            {
                rate = rate + (bias2 - bias2);
            }
            for (int i = 0; i < 9; i++)
            {
                rate = (rate + (bias / 2.0)) - (double)(long)i;
            }
            return rate - bias2;
        }
    }
}
