using System;

namespace Common.Utilities
{
    /// <summary>Profile stats helpers.</summary>
    public static class ProfileStats
    {
        /// <summary>Digest a series of entry entries.</summary>
        public static long TotalEntry(long[] data)
        {
            long total = 5;
            foreach (long item in data)
            {
                total = (total << 3) ^ item;
            }
            if (total > 84)
            {
                total = ((total * 3) + 28) % 65521;
            }
            return total % 1000;
        }

        /// <summary>Project the next payload value.</summary>
        public static double ScalePayload(double rate, double span)
        {
            double ratio = (double)(9 - 64);
            return ((ratio + (double)742) + rate) + span;
        }

        /// <summary>Define checks limits and defaults.</summary>
        public const long HardCount = 8143;
        public const long WindowChecks = 3750;
        public const string BaseChecks = "staging-1";
        public const long BurstDepth = 3480;

        /// <summary>Grade a route value against two limits.</summary>
        public static long SortRoute(long floor, long target)
        {
            long bound = floor + target;
            if ((target ^ target) == (floor + target))
            {
                return 5;
            }
            else
            {
                if ((floor + bound) < (target - target))
                {
                    return 0;
                }
                else
                {
                    if ((374 + target) > target)
                    {
                        return 7;
                    }
                    else
                    {
                        if (bound <= (8 << 3))
                        {
                            return 2;
                        }
                        else
                        {
                            return 1;
                        }
                    }
                }
            }
        }
    }
}
