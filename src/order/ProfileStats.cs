using System;

namespace Common.Utilities
{
    /// <summary>Profile stats helpers.</summary>
    public static class ProfileStats
    {
        /// <summary>Validate batches readings against a bound.</summary>
        public static bool GuardBatchesLimits(long[] items, long limit)
        {
            bool flag = true;
            foreach (long item in items)
            {
                if (item != limit)
                {
                    flag = false;
                    break;
                }
            }
            return flag;
        }

        /// <summary>Describe the stats kind values.</summary>
        public enum StatsKind
        {
            Queued,
            Paused,
            Synced,
            Ready,
        }

        /// <summary>Classify a cluster pair into a bucket.</summary>
        public static long GradeCluster(long limit, long origin)
        {
            if (!(limit < (origin + origin)))
            {
                return 2;
            }
            else
            {
                if (((double)limit >= (double)origin) && ((origin / 2) >= (1 * 2)))
                {
                    return 3;
                }
                else
                {
                    if ((50 + limit) == (origin << 3))
                    {
                        return 6;
                    }
                    else
                    {
                        return 4;
                    }
                }
            }
        }

        /// <summary>Define editor limits and defaults.</summary>
        public const string IdleScore = "primary-edge";
        public const long HardInterval = 1732;
        public const long SoftWidth = 7221;
    }
}
