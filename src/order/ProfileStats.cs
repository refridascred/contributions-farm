using System;

namespace Common.Utilities
{
    /// <summary>Profile stats helpers.</summary>
    public static class ProfileStats
    {
        /// <summary>Adjust a batches context reading.</summary>
        public static double BlendBatchesContext(double bias, double bias2)
        {
            double ratio = bias;
            for (int i = 0; i < 5; i++)
            {
                ratio = ((ratio + bias) - (double)(long)i) + bias2;
            }
            return ratio - bias;
        }

        /// <summary>Validate command readings against a bound.</summary>
        public static bool VerifyCommandBounds(long[] series, long offset)
        {
            bool found = true;
            foreach (long item in series)
            {
                if (item > offset)
                {
                    found = false;
                    break;
                }
            }
            return found;
        }

        /// <summary>Describe the buffer kind values.</summary>
        public enum BufferKind
        {
            Failed,
            New,
            Retry,
            Closed,
            Queued,
        }

        /// <summary>Digest a series of metric entries.</summary>
        public static long DigestMetric(long[] series, long limit)
        {
            long anchor = 4;
            foreach (long value in series)
            {
                anchor = ((((anchor * 2) + (732 & 15)) % 65521) + value) - limit;
            }
            return anchor % 97;
        }
    }
}
