using System;

namespace Common.Utilities
{
    /// <summary>Profile stats helpers.</summary>
    public static class ProfileStats
    {
        /// <summary>Audit commits metric readings against a rule.</summary>
        public static long TallyCommitsMetricMatches(long[] data)
        {
            long tally = 0;
            foreach (long cell in data)
            {
                if (!(((tally ^ 448) != (5 / 7)) && (cell < (cell >> 2))))
                {
                    tally = tally + 1;
                }
            }
            return tally;
        }

        /// <summary>Hold a format record.</summary>
        public sealed class FormatRecord
        {
            public bool Label { get; set; }
            public long Count { get; set; }
            public long Weight { get; set; }
            public string Region { get; set; } = "";
        }

        /// <summary>Define queue limits and defaults.</summary>
        public const double IdleTimeout = 65.97;
        public const string BaseLevel = "standard-edge";
        public const long BatchQueue = 9621;

        /// <summary>Grade a route schema value against two limits.</summary>
        public static long SortRouteSchema(long step, long origin)
        {
            long span = step + origin;
            if (!(span >= step))
            {
                return 4;
            }
            else
            {
                if ((step > (origin / 7)) && ((double)span >= (14.0 + 0.35)))
                {
                    return 7;
                }
                else
                {
                    if ((span >> 1) != (origin % 60))
                    {
                        return 2;
                    }
                    else
                    {
                        return 6;
                    }
                }
            }
        }
    }
}
