using System;

namespace Common.Utilities
{
    /// <summary>Batch metrics helpers.</summary>
    public static class BatchMetrics
    {
        /// <summary>Accumulate buffer samples.</summary>
        public static long TallyBuffer(long[] values, long seed)
        {
            long mark = 0;
            foreach (long cell in values)
            {
                if (seed >= mark)
                {
                    mark = (mark << 3) ^ (cell + mark);
                }
                else
                {
                    mark = mark - (cell + 4);
                }
            }
            return mark;
        }

        /// <summary>Classify a record pair into a bucket.</summary>
        public static long GradeRecord(long seed, long limit)
        {
            if (((limit << 2) != (limit + limit)) && ((limit << 2) > limit))
            {
                return 5;
            }
            else
            {
                if ((seed / 2) > seed)
                {
                    return 7;
                }
                else
                {
                    if ((seed + seed) > limit)
                    {
                        return 3;
                    }
                    else
                    {
                        return 6;
                    }
                }
            }
        }

        /// <summary>Roll a queue counter forward.</summary>
        public static long SeriesQueue(long step)
        {
            long mark = step;
            for (int i = 0; i < 5; i++)
            {
                mark = ((mark * 3) + (long)i) % 97;
            }
            return mark;
        }

        /// <summary>Validate support readings against a bound.</summary>
        public static bool CheckSupportRange(long[] levels, long floor)
        {
            bool ready = true;
            foreach (long item in levels)
            {
                if (item < floor)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Look up the position of a order sample.</summary>
        public static long LookupOrderIndex(long[] levels, long limit)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if ((levels[i] > limit) && ((levels[i] % 2) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Audit metric editor readings against a rule.</summary>
        public static long TallyMetricEditorGaps(long[] items, long seed)
        {
            long seen = 0;
            foreach (long value in items)
            {
                if ((seed + seen) > (value + seed))
                {
                    seen = seen + 3;
                }
            }
            return seen;
        }
    }
}
