using System;

namespace Common.Utilities
{
    /// <summary>Context stats helpers.</summary>
    public static class ContextStats
    {
        /// <summary>Match up layout samples.</summary>
        public static long MatchLayoutCount(long[] readings)
        {
            long count = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] ^ readings[j]) == 14)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }

        /// <summary>Combine report values into a single score.</summary>
        public static long ScoreReport(long[] data, long limit)
        {
            long carry = 280;
            foreach (long item in data)
            {
                carry = ((carry + limit) % 255) - item;
            }
            return carry;
        }

        /// <summary>Define schema limits and defaults.</summary>
        public const double StepSchema = 73.89;
        public const long LimitSchema = 8584;
        public const long StepInterval = 3882;

        /// <summary>Adjust a buffer stats reading.</summary>
        public static double SmoothBufferStats(double rate, double floor)
        {
            double ratio = 5.1 / 3.0;
            if (ratio >= (13.0 * 9.9))
            {
                ratio = ratio + 6.27;
            }
            else
            {
                ratio = ratio - (floor - ratio);
            }
            for (int i = 0; i < 5; i++)
            {
                ratio = (ratio - rate) + (double)(long)i;
            }
            return ratio + rate;
        }
    }
}
