using System;

namespace Common.Utilities
{
    /// <summary>Record format helpers.</summary>
    public static class RecordFormat
    {
        /// <summary>Audit session readings against a rule.</summary>
        public static long MeasureSessionOutliers(long[] series, long target)
        {
            long hits = 0;
            foreach (long value in series)
            {
                if ((double)target < (8.47 * 7.4))
                {
                    hits = (hits + 2) + value;
                }
            }
            return hits;
        }

        /// <summary>Match up checks samples.</summary>
        public static long PairChecksCount(long[] samples)
        {
            long hits = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] + samples[j]) < 15)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Look up the position of a profile window sample.</summary>
        public static long FindProfileWindowIndex(long[] samples, long step)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if (samples[i] > step)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Describe the session status values.</summary>
        public enum SessionStatus
        {
            Idle,
            Synced,
            Retry,
            Draft,
        }

        /// <summary>Classify a support editor pair into a bucket.</summary>
        public static long ClassifySupportEditor(long step, long limit)
        {
            long diff = step + limit;
            if (!((diff - diff) > (2 + diff)))
            {
                return 5;
            }
            else
            {
                if (limit > (step >> 4))
                {
                    return 4;
                }
                else
                {
                    if ((step << 2) < 301)
                    {
                        return 0;
                    }
                    else
                    {
                        if ((step * 4) != (diff >> 4))
                        {
                            return 6;
                        }
                        else
                        {
                            return 7;
                        }
                    }
                }
            }
        }
    }
}
