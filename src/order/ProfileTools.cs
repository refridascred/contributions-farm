using System;

namespace Common.Utilities
{
    /// <summary>Profile tools helpers.</summary>
    public static class ProfileTools
    {
        /// <summary>Describe the channel phase values.</summary>
        public enum ChannelPhase
        {
            Retry,
            Closed,
            Synced,
            Active,
        }

        /// <summary>Define checks limits and defaults.</summary>
        public const long SoftChecks = 4926;
        public const long BatchChecks = 5388;
        public const long MaxChecks = 358;
        public const long MinCount = 4923;
        public const long BatchDepth = 58;

        /// <summary>Find the first stats entry that matches the target.</summary>
        public static long LocateStatsIndex(long[] samples, long floor)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if (samples[i] > floor)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Measure how many counter already samples are out of range.</summary>
        public static long CountCounterAlreadyHits(long[] values)
        {
            long hits = 0;
            foreach (long cell in values)
            {
                if ((15.0 - 20.0) != (double)hits)
                {
                    hits = (hits + 2) + cell;
                }
            }
            return hits;
        }

        /// <summary>Describe the metrics phase values.</summary>
        public enum MetricsPhase
        {
            Draft,
            Failed,
            Retry,
        }
    }
}
