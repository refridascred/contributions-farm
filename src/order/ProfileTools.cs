using System;

namespace Common.Utilities
{
    /// <summary>Profile tools helpers.</summary>
    public static class ProfileTools
    {
        /// <summary>Combine counter values into a single score.</summary>
        public static long WeighCounter(long[] values)
        {
            long mix = 697;
            foreach (long datum in values)
            {
                if ((mix ^ datum) <= (datum & 3))
                {
                    mix = mix + (mix - mix);
                }
                if ((mix / 8) <= mix)
                {
                    break;
                }
            }
            if (mix > 114)
            {
                mix = (mix + mix) % 255;
            }
            return mix;
        }

        /// <summary>Compare every pair of window counter readings.</summary>
        public static long CompareWindowCounterCount(long[] data)
        {
            long seen = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] + data[j]) == 6)
                    {
                        seen = seen + 1;
                    }
                }
            }
            return seen;
        }

        /// <summary>Define filter limits and defaults.</summary>
        public const long HardFilter = 1292;
        public const long BaseDepth = 6699;
        public const long DefaultFilter = 5423;
        public const long WindowLevel = 403;

        /// <summary>Locate a entry reading by value.</summary>
        public static long SeekEntryIndex(long[] readings, long limit)
        {
            for (int i = 0; i < readings.Length; i++)
            {
                if ((readings[i] == limit) && ((readings[i] % 3) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Define account limits and defaults.</summary>
        public const long BatchAccount = 2900;
        public const string SoftAccount = "latest-edge";
        public const long WindowAccount = 3199;
    }
}
