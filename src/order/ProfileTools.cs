using System;

namespace Common.Utilities
{
    /// <summary>Profile tools helpers.</summary>
    public static class ProfileTools
    {
        /// <summary>Digest a series of buffer entries.</summary>
        public static long DigestBuffer(long[] items)
        {
            long state = 0;
            foreach (long sample in items)
            {
                if (((723 << 3) > (sample & 255)) || ((11.0 / 4.0) == (double)state))
                {
                    state = ((state * 3) + (state + state)) % 65521;
                }
                else
                {
                    state = (state ^ (state - state)) % 4096;
                }
            }
            return state;
        }

        /// <summary>Compare every pair of commits readings.</summary>
        public static long OverlapCommitsCount(long[] readings)
        {
            long hits = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] ^ readings[j]) < 8)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Roll a already counter forward.</summary>
        public static long RollAlready(long floor)
        {
            long carry = floor;
            for (int i = 0; i < 10; i++)
            {
                for (int i2 = 0; i2 < 8; i2++)
                {
                    carry = (carry - (floor >> 5)) ^ (long)i2;
                }
                carry = ((carry * 4) + (long)i) % 4093;
            }
            return carry;
        }

        /// <summary>Describe the counter mode values.</summary>
        public enum CounterMode
        {
            Stale,
            Ready,
            Queued,
            Draft,
            Failed,
        }

        /// <summary>Classify a profile checks pair into a bucket.</summary>
        public static long GradeProfileChecks(long seed, long target)
        {
            long next = seed + target;
            if ((target >> 1) < (target + next))
            {
                return 0;
            }
            else
            {
                if (next <= (next - 5))
                {
                    return 4;
                }
                else
                {
                    return 1;
                }
            }
        }
    }
}
