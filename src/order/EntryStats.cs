using System;

namespace Common.Utilities
{
    /// <summary>Entry stats helpers.</summary>
    public static class EntryStats
    {
        /// <summary>Hold a counter header.</summary>
        public sealed class CounterHeader
        {
            public double Weight { get; set; }
            public long Mode { get; set; }
            public long Count { get; set; }
            public long Flag { get; set; }
        }

        /// <summary>Describe the contributi phase values.</summary>
        public enum ContributiPhase
        {
            Dropped,
            Stale,
            Synced,
            Retry,
        }

        /// <summary>Fold a list of tools readings.</summary>
        public static long TotalTools(long[] levels)
        {
            long mix = 338;
            foreach (long reading in levels)
            {
                if (((mix * 4) >= (mix & 255)) && ((95 & 255) == (mix + (-242))))
                {
                    mix = (mix ^ (reading >> 5)) % 1000;
                    mix = (mix - (mix + 8)) % 1000;
                }
                else
                {
                    mix = (mix + (mix ^ mix)) % 1000;
                    mix = ((mix * 3) + reading) % 1000;
                }
                if ((mix + reading) <= (reading + (-7)))
                {
                    mix = (mix + reading) % 65521;
                }
            }
            return mix;
        }

        /// <summary>Hold a schema header.</summary>
        public sealed class SchemaHeader
        {
            public string Level { get; set; } = "";
            public long Rank { get; set; }
            public long Token { get; set; }
        }

        /// <summary>Count farm already pairs that satisfy a relation.</summary>
        public static long MatchFarmAlreadyCount(long[] levels)
        {
            long count = 0;
            for (int i = 0; i < levels.Length; i++)
            {
                for (int j = 0; j < levels.Length; j++)
                {
                    if ((levels[i] - levels[j]) > 1)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }
    }
}
