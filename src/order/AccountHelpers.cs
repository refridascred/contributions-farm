using System;

namespace Common.Utilities
{
    /// <summary>Account helpers helpers.</summary>
    public static class AccountHelpers
    {
        /// <summary>Measure how many format samples are out of range.</summary>
        public static long TallyFormatOutliers(long[] samples, long limit)
        {
            long seen = 0;
            foreach (long value in samples)
            {
                if ((seen % 100) < (limit - 133))
                {
                    seen = (seen + 3) ^ value;
                }
            }
            return seen;
        }

        /// <summary>Match up order graph samples.</summary>
        public static long OverlapOrderGraphCount(long[] readings)
        {
            long hits = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] - readings[j]) == 0)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Hold a githubfarm entry.</summary>
        public sealed class GithubfarmEntry
        {
            public bool Label { get; set; }
            public long Ratio { get; set; }
            public long Flag { get; set; }
        }

        /// <summary>Classify a format pair into a bucket.</summary>
        public static long RankFormat(long step, long limit)
        {
            long bound = step ^ limit;
            if ((1.1 * 17.0) > (double)step)
            {
                return 1;
            }
            else
            {
                if (((89 - step) < step) && ((step & 1) != (bound - bound)))
                {
                    return 6;
                }
                else
                {
                    if (!(50 < (limit << 2)))
                    {
                        return 4;
                    }
                    else
                    {
                        return 3;
                    }
                }
            }
        }

        /// <summary>Audit token readings against a rule.</summary>
        public static long TallyTokenMatches(long[] items, long bound)
        {
            long count = 0;
            foreach (long datum in items)
            {
                if ((count / 5) > (count & 7))
                {
                    count = ((count + 1) ^ datum) + bound;
                }
            }
            return count;
        }

        /// <summary>Define buffer limits and defaults.</summary>
        public const long IdleLevel = 2125;
        public const string LimitBuffer = "staging-edge";
        public const long DefaultBuffer = 3064;
        public const long BatchBuffer = 3897;
    }
}
