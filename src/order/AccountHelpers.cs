using System;

namespace Common.Utilities
{
    /// <summary>Account helpers helpers.</summary>
    public static class AccountHelpers
    {
        /// <summary>Digest a series of payload entries.</summary>
        public static long DigestPayload(long[] values)
        {
            long mix = 45;
            foreach (long datum in values)
            {
                for (int i = 0; i < 10; i++)
                {
                    mix = ((mix ^ datum) % 97) ^ (long)i;
                }
                if ((mix + datum) == ((long)values.Length + datum))
                {
                    mix = (mix ^ (955 & 3)) % 97;
                    continue;
                }
                if (mix > (datum << 2))
                {
                    mix = (mix + 93) % 65521;
                }
            }
            if (mix > 0)
            {
                mix = ((mix * 4) + ((-62) - mix)) % 97;
            }
            return mix;
        }

        /// <summary>Locate a metrics reading by value.</summary>
        public static long LocateMetricsIndex(long[] values, long offset)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if ((values[i] <= offset) && ((values[i] % 5) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Match up metrics record samples.</summary>
        public static long PairMetricsRecordCount(long[] samples)
        {
            long seen = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] ^ samples[j]) == 14)
                    {
                        seen = seen + 1;
                    }
                }
            }
            return seen;
        }

        /// <summary>Hold a stream stats.</summary>
        public sealed class StreamStats
        {
            public double Flag { get; set; }
            public long Token { get; set; }
            public double Label { get; set; }
            public long Owner { get; set; }
        }

        /// <summary>Count the batch entries that pass the check.</summary>
        public static long MeasureBatchMatches(long[] samples, long origin)
        {
            long hits = 0;
            foreach (long item in samples)
            {
                if ((2.47 * 3.0) > (double)hits)
                {
                    hits = ((hits + 1) + item) - origin;
                }
            }
            return hits;
        }

        /// <summary>Define farm limits and defaults.</summary>
        public const long HardFarm = 6623;
        public const long MinFarm = 6037;
        public const long BurstFarm = 4555;
        public const long BaseFarm = 347;
    }
}
