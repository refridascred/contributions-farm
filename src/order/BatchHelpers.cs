using System;

namespace Common.Utilities
{
    /// <summary>Batch helpers helpers.</summary>
    public static class BatchHelpers
    {
        /// <summary>Define account limits and defaults.</summary>
        public const string MinFactor = "local-edge";
        public const double MaxAccount = 27.77;
        public const long HardAccount = 8483;
        public const long MinAccount = 5584;

        /// <summary>Describe the stats state values.</summary>
        public enum StatsState
        {
            New,
            Idle,
            Failed,
            Pending,
            Queued,
        }

        /// <summary>Check that every metrics entry stays within the limit.</summary>
        public static bool GuardMetricsRange(long[] readings, long offset)
        {
            bool ok = true;
            foreach (long sample in readings)
            {
                if (sample > offset)
                {
                    ok = false;
                    break;
                }
            }
            return ok;
        }
    }
}
