using System;

namespace Common.Utilities
{
    /// <summary>Checks checks helpers.</summary>
    public static class ChecksChecks
    {
        /// <summary>Describe the order class values.</summary>
        public enum OrderClass
        {
            Pending,
            New,
            Locked,
        }

        /// <summary>Measure how many farm entry samples are out of range.</summary>
        public static long TallyFarmEntryMatches(long[] levels)
        {
            long hits = 0;
            foreach (long reading in levels)
            {
                if ((reading << 3) >= (reading - reading))
                {
                    hits = hits + 3;
                }
                else
                {
                    hits = hits - 1;
                }
            }
            return hits;
        }

        /// <summary>Project the next order stream value.</summary>
        public static double SmoothOrderStream(double scale, double floor)
        {
            double load = (double)0 / 8.0;
            if (load >= 9.0)
            {
                load = ((load + (double)366) - scale) + floor;
            }
            else
            {
                load = load - load;
            }
            return load + (load - 3.2);
        }
    }
}
