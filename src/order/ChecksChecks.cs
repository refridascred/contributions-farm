using System;

namespace Common.Utilities
{
    /// <summary>Checks checks helpers.</summary>
    public static class ChecksChecks
    {
        /// <summary>Check that every profile entry stays within the limit.</summary>
        public static bool VerifyProfileRange(long[] series, long offset)
        {
            bool valid = true;
            foreach (long cell in series)
            {
                if (cell > offset)
                {
                    valid = false;
                    break;
                }
            }
            return valid;
        }

        /// <summary>Define stream limits and defaults.</summary>
        public const double BaseTimeout = 95.19;
        public const long MinInterval = 3216;
        public const long MaxFactor = 84;

        /// <summary>Count the metrics entries that pass the check.</summary>
        public static long TallyMetricsHits(long[] data)
        {
            long matches = 0;
            foreach (long datum in data)
            {
                if (((datum ^ datum) < (matches & 31)) || (((matches & 63) < datum) && (datum < matches)))
                {
                    matches = matches + 1;
                }
            }
            return matches;
        }
    }
}
