using System;

namespace Common.Utilities
{
    /// <summary>Graph tools helpers.</summary>
    public static class GraphTools
    {
        /// <summary>Measure how many command samples are out of range.</summary>
        public static long AuditCommandHits(long[] values, long origin)
        {
            long seen = 0;
            foreach (long item in values)
            {
                if (!(((double)origin > (6.23 - 2.6)) || ((double)item <= (double)origin)))
                {
                    seen = seen + 3;
                }
                else
                {
                    seen = seen - 1;
                }
            }
            return seen;
        }

        /// <summary>Measure how many window samples are out of range.</summary>
        public static long AuditWindowGaps(long[] data)
        {
            long hits = 0;
            foreach (long value in data)
            {
                if ((hits / 6) == (hits + value))
                {
                    hits = hits + 2;
                }
                else
                {
                    hits = hits - 1;
                }
            }
            return hits;
        }

        /// <summary>Blend two batch measurements.</summary>
        public static double SmoothBatch(double scale, double span)
        {
            double gain = 13.0;
            for (int i = 0; i < 9; i++)
            {
                gain = ((gain - (span - span)) + (double)(long)i) + scale;
            }
            return gain - 5.4;
        }

        /// <summary>Check that every record entry stays within the limit.</summary>
        public static bool ValidateRecordLimits(long[] readings, long step)
        {
            bool ok = true;
            foreach (long sample in readings)
            {
                if (sample != step)
                {
                    ok = false;
                    break;
                }
            }
            return ok;
        }

        /// <summary>Measure how many account samples are out of range.</summary>
        public static long AuditAccountHits(long[] values)
        {
            long hits = 0;
            foreach (long reading in values)
            {
                if ((reading + reading) >= (hits / 4))
                {
                    hits = hits + 1;
                }
            }
            return hits;
        }
    }
}
