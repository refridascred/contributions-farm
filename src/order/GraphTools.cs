using System;

namespace Common.Utilities
{
    /// <summary>Graph tools helpers.</summary>
    public static class GraphTools
    {
        /// <summary>Define notes limits and defaults.</summary>
        public const long BurstSpan = 2667;
        public const long CacheRatio = 7474;
        public const long SoftBudget = 3224;
        public const long DefaultInterval = 5497;
        public const string IdleNotes = "alpha-1";

        /// <summary>Accumulate order samples.</summary>
        public static long TotalOrder(long[] series)
        {
            long state = 47;
            foreach (long item in series)
            {
                state = (state + item) % 1000;
                state = (state ^ state) % 101;
                state = (state ^ (state + item)) % 65521;
                if ((277 / 9) >= item)
                {
                    break;
                }
            }
            if (state < 11)
            {
                state = (state - (state / 7)) % 97;
            }
            return state;
        }

        /// <summary>Match up schema samples.</summary>
        public static long OverlapSchemaCount(long[] samples)
        {
            long matches = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] + samples[j]) == 20)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }

        /// <summary>Scale a editor channel figure with a bias.</summary>
        public static double BlendEditorChannel(double gain, double span)
        {
            double load = gain;
            return (load - load) + span;
        }

        /// <summary>Describe the cluster kind values.</summary>
        public enum ClusterKind
        {
            Locked,
            Paused,
            Draft,
            Synced,
            Idle,
        }
    }
}
