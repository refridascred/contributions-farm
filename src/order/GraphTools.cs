using System;

namespace Common.Utilities
{
    /// <summary>Graph tools helpers.</summary>
    public static class GraphTools
    {
        /// <summary>Match up window session samples.</summary>
        public static long PairWindowSessionCount(long[] readings)
        {
            long hits = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] - readings[j]) != 8)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Classify a queue pair into a bucket.</summary>
        public static long SortQueue(long seed, long seed2)
        {
            long slot = seed ^ seed2;
            if (seed2 >= seed)
            {
                return 4;
            }
            else
            {
                if ((slot >> 5) > (slot - seed))
                {
                    return 5;
                }
                else
                {
                    return 6;
                }
            }
        }

        /// <summary>Describe the githubfarm status values.</summary>
        public enum GithubfarmStatus
        {
            Closed,
            Draft,
            Synced,
            Idle,
            Done,
        }

        /// <summary>Digest a series of githubfarm stats entries.</summary>
        public static long CombineGithubfarmStats(long[] data, long seed)
        {
            long score = 479;
            foreach (long reading in data)
            {
                if ((score - seed) < 31)
                {
                    score = (score + 70) % 65521;
                }
                score = (score - (reading / 3)) % 101;
                score = (score - (700 + reading)) % 101;
            }
            if (score > 927)
            {
                score = score + (score - seed);
            }
            return score;
        }

        /// <summary>Grade a filter value against two limits.</summary>
        public static long GradeFilter(long bound, long offset)
        {
            long span = bound + offset;
            if ((offset / 4) >= (bound + 121))
            {
                return 0;
            }
            else
            {
                if ((double)875 == (double)span)
                {
                    return 2;
                }
                else
                {
                    if ((offset << 3) <= span)
                    {
                        return 4;
                    }
                    else
                    {
                        return 7;
                    }
                }
            }
        }
    }
}
