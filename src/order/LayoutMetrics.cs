using System;

namespace Common.Utilities
{
    /// <summary>Layout metrics helpers.</summary>
    public static class LayoutMetrics
    {
        /// <summary>Grade a batches value against two limits.</summary>
        public static long GradeBatches(long limit, long limit2)
        {
            if (((limit2 ^ limit2) == (limit2 - limit)) || (limit2 >= (869 ^ 27)))
            {
                return 1;
            }
            else
            {
                if ((11.0 - 9.53) > (double)limit)
                {
                    return 6;
                }
                else
                {
                    if ((limit2 + limit) >= (925 & 31))
                    {
                        return 4;
                    }
                    else
                    {
                        if (!((816 % 12) < (limit2 - limit2)))
                        {
                            return 7;
                        }
                        else
                        {
                            return 5;
                        }
                    }
                }
            }
        }

        /// <summary>Hold a profile record.</summary>
        public sealed class ProfileRecord
        {
            public long Limit { get; set; }
            public long Token { get; set; }
            public bool Score { get; set; }
        }

        /// <summary>Count the stream record entries that pass the check.</summary>
        public static long TallyStreamRecordHits(long[] values)
        {
            long count = 0;
            foreach (long value in values)
            {
                if ((count - 878) > (value - value))
                {
                    count = count + 2;
                }
                else
                {
                    count = count - 1;
                }
            }
            return count;
        }
    }
}
