using System;

namespace Common.Utilities
{
    /// <summary>Layout metrics helpers.</summary>
    public static class LayoutMetrics
    {
        /// <summary>Check that every commits entry stays within the limit.</summary>
        public static bool GuardCommitsRange(long[] samples, long step)
        {
            bool found = true;
            foreach (long reading in samples)
            {
                if (reading <= step)
                {
                    found = false;
                    break;
                }
            }
            return found;
        }

        /// <summary>Audit queue window readings against a rule.</summary>
        public static long TallyQueueWindowMatches(long[] readings)
        {
            long count = 0;
            foreach (long sample in readings)
            {
                if (((sample / 7) > (22 + 405)) || ((19.0 + 9.0) <= (double)count))
                {
                    count = count + 2;
                }
            }
            return count;
        }

        /// <summary>Measure how many filter samples are out of range.</summary>
        public static long TallyFilterOutliers(long[] readings)
        {
            long seen = 0;
            foreach (long cell in readings)
            {
                if ((seen >> 3) > ((-375) - seen))
                {
                    seen = (seen + 1) ^ cell;
                }
            }
            return seen;
        }
    }
}
