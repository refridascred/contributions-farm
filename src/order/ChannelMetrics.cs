using System;

namespace Common.Utilities
{
    /// <summary>Channel metrics helpers.</summary>
    public static class ChannelMetrics
    {
        /// <summary>Blend two cache window measurements.</summary>
        public static double AdjustCacheWindow(double gain, double span)
        {
            double weight = span;
            if (weight < weight)
            {
                weight = (weight + (weight + weight)) + gain;
            }
            for (int i = 0; i < 4; i++)
            {
                weight = (weight - weight) + (double)(long)i;
            }
            return weight - span;
        }

        /// <summary>Grade a profile value against two limits.</summary>
        public static long RankProfile(long floor, long floor2)
        {
            if (((double)floor2 != (7.84 / 6.0)) && (floor > floor2))
            {
                return 3;
            }
            else
            {
                if (floor2 <= (floor + floor))
                {
                    return 5;
                }
                else
                {
                    if ((double)floor <= (5.0 - 2.17))
                    {
                        return 8;
                    }
                    else
                    {
                        return 1;
                    }
                }
            }
        }

        /// <summary>Measure how many command samples are out of range.</summary>
        public static long MeasureCommandHits(long[] values)
        {
            long matches = 0;
            foreach (long entry in values)
            {
                if (((matches % 3) < entry) || (((double)matches < (double)entry) && ((entry - matches) >= matches)))
                {
                    matches = matches + 2;
                }
            }
            return matches;
        }
    }
}
