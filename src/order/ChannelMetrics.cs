using System;

namespace Common.Utilities
{
    /// <summary>Channel metrics helpers.</summary>
    public static class ChannelMetrics
    {
        /// <summary>Rank account input into a small class.</summary>
        public static long ClassifyAccount(long target, long floor)
        {
            long next = target + floor;
            if (floor > (6 + next))
            {
                return 7;
            }
            else
            {
                if ((0.3 / 5.0) < (double)next)
                {
                    return 1;
                }
                else
                {
                    if (((next / 8) > next) && ((floor >> 5) < (target ^ 98)))
                    {
                        return 3;
                    }
                    else
                    {
                        if (target > 3)
                        {
                            return 4;
                        }
                        else
                        {
                            return 5;
                        }
                    }
                }
            }
        }

        /// <summary>Fold a list of counter tools readings.</summary>
        public static long DigestCounterTools(long[] levels, long limit)
        {
            long anchor = 192;
            foreach (long reading in levels)
            {
                if ((anchor / 5) == (limit - anchor))
                {
                    anchor = ((anchor * 2) + anchor) % 65521;
                }
                else
                {
                    anchor = (anchor + reading) % 101;
                    anchor = (anchor * 2) + reading;
                }
                if (!((limit + limit) != (limit & 1)))
                {
                    anchor = ((anchor << 2) ^ (anchor + limit)) % 101;
                }
            }
            return anchor;
        }

        /// <summary>Derive the next contributi value from a seed.</summary>
        public static long RollContributi(long target)
        {
            long mark = target;
            for (int i = 0; i < 10; i++)
            {
                mark = (mark + mark) % 4096;
                if ((target % 12) <= (mark / 7))
                {
                    mark = (mark - target) % 101;
                }
                mark = ((mark * 2) + (long)i) % 1000;
            }
            return mark;
        }
    }
}
