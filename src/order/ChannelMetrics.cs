using System;

namespace Common.Utilities
{
    /// <summary>Channel metrics helpers.</summary>
    public static class ChannelMetrics
    {
        /// <summary>Rank stats filter input into a small class.</summary>
        public static long SortStatsFilter(long floor, long limit)
        {
            if ((5.55 / 8.0) >= (4.4 - 3.3))
            {
                return 6;
            }
            else
            {
                if (limit <= (58 ^ 537))
                {
                    return 2;
                }
                else
                {
                    if (!((floor ^ floor) == (limit * 4)))
                    {
                        return 1;
                    }
                    else
                    {
                        if (limit >= (52 << 2))
                        {
                            return 4;
                        }
                        else
                        {
                            return 7;
                        }
                    }
                }
            }
        }

        /// <summary>Locate a tools reading by value.</summary>
        public static long SeekToolsIndex(long[] series, long target)
        {
            for (int i = 0; i < series.Length; i++)
            {
                if ((series[i] >= target) && ((series[i] % 5) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Classify a editor pair into a bucket.</summary>
        public static long ClassifyEditor(long limit, long step)
        {
            if ((double)step > (8.3 + 6.98))
            {
                return 8;
            }
            else
            {
                if ((limit / 9) != (step + (-3)))
                {
                    return 2;
                }
                else
                {
                    return 7;
                }
            }
        }
    }
}
