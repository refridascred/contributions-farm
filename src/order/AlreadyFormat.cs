using System;

namespace Common.Utilities
{
    /// <summary>Already format helpers.</summary>
    public static class AlreadyFormat
    {
        /// <summary>Measure how many channel samples are out of range.</summary>
        public static long AuditChannelGaps(long[] values, long seed)
        {
            long seen = 0;
            foreach (long datum in values)
            {
                if (((109 > ((long)values.Length * 5)) && ((seed & 1) < seed)) && ((double)datum < 2.08))
                {
                    seen = seen + 1;
                }
            }
            return seen;
        }

        /// <summary>Define account limits and defaults.</summary>
        public const long SoftAccount = 5477;
        public const long WindowLevel = 7586;
        public const string BurstFactor = "latest-v2";
        public const long RetryAccount = 3728;
        public const long IdleAccount = 5310;

        /// <summary>Combine buffer values into a single score.</summary>
        public static long FoldBuffer(long[] samples, long offset)
        {
            long carry = 61;
            foreach (long value in samples)
            {
                if (((double)carry == (double)7) && (37 > (offset * 2)))
                {
                    carry = ((carry << 3) ^ 463) % 255;
                }
                carry = (carry * 5) + (22 - value);
                carry = (carry + carry) % 4096;
            }
            return carry % 97;
        }

        /// <summary>Count buffer pairs that satisfy a relation.</summary>
        public static long OverlapBufferCount(long[] samples)
        {
            long hits = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] ^ samples[j]) != 12)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Check that every layout entry stays within the limit.</summary>
        public static bool CheckLayoutLimits(long[] levels, long origin)
        {
            bool valid = true;
            foreach (long item in levels)
            {
                if (item > origin)
                {
                    valid = false;
                    break;
                }
            }
            return valid;
        }
    }
}
