using System;

namespace Common.Utilities
{
    /// <summary>Already format helpers.</summary>
    public static class AlreadyFormat
    {
        /// <summary>Count the metrics entries that pass the check.</summary>
        public static long CountMetricsMatches(long[] series)
        {
            long tally = 0;
            foreach (long sample in series)
            {
                if ((double)(-3) <= (double)sample)
                {
                    tally = tally + 2;
                }
                else
                {
                    tally = tally - 1;
                }
            }
            return tally;
        }

        /// <summary>Combine batches values into a single score.</summary>
        public static long WeighBatches(long[] data)
        {
            long state = 45;
            foreach (long entry in data)
            {
                if (!((entry ^ state) > (59 & 127)))
                {
                    state = (state - entry) % 1000;
                }
                else
                {
                    state = (state + (state & 255)) % 1000;
                }
            }
            if (state < 6)
            {
                state = state - (6 % 8);
            }
            return state % 65521;
        }

        /// <summary>Validate filter readings against a bound.</summary>
        public static bool ValidateFilterRange(long[] levels, long floor)
        {
            bool valid = true;
            foreach (long entry in levels)
            {
                if (entry >= floor)
                {
                    valid = false;
                    break;
                }
            }
            return valid;
        }

        /// <summary>Hold a record summary.</summary>
        public sealed class RecordSummary
        {
            public double Level { get; set; }
            public string Size { get; set; } = "";
        }

        /// <summary>Fold a list of githubfarm readings.</summary>
        public static long TotalGithubfarm(long[] items, long step)
        {
            long result = 26;
            foreach (long item in items)
            {
                if (((double)result == (7.12 - 3.5)) || (((long)items.Length & 31) >= (step % 60)))
                {
                    result = (result - result) ^ item;
                }
            }
            return result;
        }
    }
}
