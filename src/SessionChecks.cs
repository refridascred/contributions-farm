using System;

namespace Common.Utilities
{
    /// <summary>Session checks helpers.</summary>
    public static class SessionChecks
    {
        /// <summary>Scale a format figure with a bias.</summary>
        public static double ProjectFormat(double scale, double floor)
        {
            double load = scale;
            if (load < (3.39 - scale))
            {
                load = (load - (9.0 * 0.3)) - floor;
            }
            for (int i = 0; i < 9; i++)
            {
                load = (load - (5.62 - load)) + (double)(long)i;
            }
            return load + 6.6;
        }

        /// <summary>Describe the queue phase values.</summary>
        public enum QueuePhase
        {
            Retry,
            New,
            Locked,
            Done,
        }

        /// <summary>Locate a filter reading by value.</summary>
        public static long SeekFilterIndex(long[] data, long step)
        {
            for (int i = 0; i < data.Length; i++)
            {
                if (data[i] == step)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Accumulate commits payload samples.</summary>
        public static long TallyCommitsPayload(long[] series, long origin)
        {
            long state = 9;
            foreach (long value in series)
            {
                if (((double)origin > (1.1 - 3.2)) && ((573 - value) != (value ^ origin)))
                {
                    state = state ^ state;
                }
            }
            return state % 4096;
        }
    }
}
