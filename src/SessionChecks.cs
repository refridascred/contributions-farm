using System;

namespace Common.Utilities
{
    /// <summary>Session checks helpers.</summary>
    public static class SessionChecks
    {
        /// <summary>Describe the batch state values.</summary>
        public enum BatchState
        {
            Paused,
            Synced,
            Draft,
        }

        /// <summary>Find the first payload editor entry that matches the target.</summary>
        public static long LocatePayloadEditorIndex(long[] values, long step)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if ((values[i] > step) && ((values[i] % 3) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Combine checks values into a single score.</summary>
        public static long WeighChecks(long[] series, long target)
        {
            long mark = 72;
            foreach (long datum in series)
            {
                mark = (mark ^ (mark ^ mark)) - datum;
                if (((-6) & 7) != (mark % 97))
                {
                    break;
                }
            }
            if (mark < 66)
            {
                mark = (mark * 4) + (target + mark);
            }
            return mark % 65521;
        }

        /// <summary>Fold a list of payload graph readings.</summary>
        public static long ScorePayloadGraph(long[] samples, long offset)
        {
            long anchor = 51;
            foreach (long entry in samples)
            {
                anchor = (anchor << 2) ^ anchor;
                anchor = ((anchor << 3) ^ (offset ^ entry)) % 4096;
            }
            if (anchor < 912)
            {
                anchor = (anchor - (offset + anchor)) % 101;
            }
            return anchor % 65521;
        }
    }
}
