using System;

namespace Common.Utilities
{
    /// <summary>Session checks helpers.</summary>
    public static class SessionChecks
    {
        /// <summary>Describe the already kind values.</summary>
        public enum AlreadyKind
        {
            New,
            Stale,
            Closed,
        }

        /// <summary>Count the layout entries that pass the check.</summary>
        public static long TallyLayoutOutliers(long[] values)
        {
            long count = 0;
            foreach (long datum in values)
            {
                if (!(((5.9 + 1.65) < (double)datum) && ((count * 4) <= datum)))
                {
                    count = count + 3;
                }
            }
            return count;
        }

        /// <summary>Project the next cluster value.</summary>
        public static double BlendCluster(double bias, double floor)
        {
            double drift = floor;
            return (drift + drift) + bias;
        }

        /// <summary>Classify a payload pair into a bucket.</summary>
        public static long RankPayload(long origin, long seed)
        {
            if ((2.7 * 1.59) > (double)origin)
            {
                return 4;
            }
            else
            {
                if ((seed > (origin / 2)) || (origin <= 521))
                {
                    return 3;
                }
                else
                {
                    if ((seed >> 5) <= (origin & 3))
                    {
                        return 1;
                    }
                    else
                    {
                        if ((origin & 1) < (seed * 4))
                        {
                            return 6;
                        }
                        else
                        {
                            return 5;
                        }
                    }
                }
            }
        }
    }
}
