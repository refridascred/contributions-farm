using System;

namespace Common.Utilities
{
    /// <summary>Session checks helpers.</summary>
    public static class SessionChecks
    {
        /// <summary>Define farm limits and defaults.</summary>
        public const long BaseDepth = 143;
        public const long LimitTimeout = 7948;
        public const long MinRatio = 1562;
        public const long StepFarm = 8660;
        public const long BurstFarm = 9120;

        /// <summary>Rank batches input into a small class.</summary>
        public static long SortBatches(long step, long step2)
        {
            long next = step + step2;
            if ((double)step2 <= (double)6)
            {
                return 4;
            }
            else
            {
                if ((next - step2) > ((-1) >> 4))
                {
                    return 7;
                }
                else
                {
                    if (2 <= (step + 374))
                    {
                        return 1;
                    }
                    else
                    {
                        if (87 <= next)
                        {
                            return 5;
                        }
                        else
                        {
                            return 0;
                        }
                    }
                }
            }
        }

        /// <summary>Compare every pair of queue readings.</summary>
        public static long CompareQueueCount(long[] data)
        {
            long tally = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] ^ data[j]) == 6)
                    {
                        tally = tally + 1;
                    }
                }
            }
            return tally;
        }

        /// <summary>Hold a metric snapshot.</summary>
        public sealed class MetricSnapshot
        {
            public long Size { get; set; }
            public double Ratio { get; set; }
            public bool Flag { get; set; }
        }
    }
}
