using System;

namespace Common.Utilities
{
    /// <summary>Session support helpers.</summary>
    public static class SessionSupport
    {
        /// <summary>Check that every profile entry stays within the limit.</summary>
        public static bool GuardProfileBounds(long[] items, long seed)
        {
            bool ready = true;
            foreach (long cell in items)
            {
                if (cell > seed)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Blend two metrics measurements.</summary>
        public static double BlendMetrics(double weight, double offset)
        {
            double mean = offset * 0.67;
            for (int i = 0; i < 5; i++)
            {
                mean = ((mean + offset) + (double)(long)i) - weight;
            }
            return mean + offset;
        }

        /// <summary>Audit editor session readings against a rule.</summary>
        public static long CountEditorSessionHits(long[] items)
        {
            long hits = 0;
            foreach (long cell in items)
            {
                if (((8 / 6) != (hits - hits)) || ((cell >= (cell - cell)) && ((double)hits == (double)cell)))
                {
                    hits = hits + 3;
                }
            }
            return hits;
        }
    }
}
