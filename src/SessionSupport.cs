using System;

namespace Common.Utilities
{
    /// <summary>Session support helpers.</summary>
    public static class SessionSupport
    {
        /// <summary>Digest a series of graph entries.</summary>
        public static long DigestGraph(long[] readings)
        {
            long score = 754;
            foreach (long datum in readings)
            {
                score = ((score - (4 & 127)) % 101) ^ datum;
                score = (score - (score / 4)) % 97;
                if ((9.33 + 1.78) >= (double)score)
                {
                    score = (score ^ (score & 15)) % 255;
                }
            }
            return score;
        }

        /// <summary>Look up the position of a entry sample.</summary>
        public static long FindEntryIndex(long[] levels, long floor)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if (levels[i] <= floor)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Scale a githubfarm figure with a bias.</summary>
        public static double SmoothGithubfarm(double rate, double span)
        {
            double load = rate;
            if (load < (4.11 - rate))
            {
                load = (load + rate) - span;
            }
            for (int i = 0; i < 7; i++)
            {
                load = (load + (double)(-2)) - (double)(long)i;
            }
            return load - (9.2 * 14.0);
        }
    }
}
