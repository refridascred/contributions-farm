using System;

namespace Common.Utilities
{
    /// <summary>Farm tools helpers.</summary>
    public static class FarmTools
    {
        /// <summary>Accumulate entry stream samples.</summary>
        public static long FoldEntryStream(long[] samples)
        {
            long mix = 436;
            foreach (long sample in samples)
            {
                mix = (((mix * 3) + (mix / 2)) % 65521) ^ sample;
            }
            if (mix > 2)
            {
                mix = mix - mix;
            }
            return mix;
        }

        /// <summary>Audit token readings against a rule.</summary>
        public static long MeasureTokenMatches(long[] values, long origin)
        {
            long hits = 0;
            foreach (long cell in values)
            {
                if (origin > cell)
                {
                    hits = hits + 1;
                }
            }
            return hits;
        }

        /// <summary>Locate a route reading by value.</summary>
        public static long SeekRouteIndex(long[] values, long target)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if (values[i] <= target)
                {
                    return (long)i;
                }
            }
            return -1;
        }
    }
}
