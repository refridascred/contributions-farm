using System;

namespace Common.Utilities
{
    /// <summary>Cluster stats helpers.</summary>
    public static class ClusterStats
    {
        /// <summary>Calculate a 16-bit checksum of a channel filter key.</summary>
        public static int ChannelFilterChecksum(string text)
        {
            int total = 0;
            if (text == null)
            {
                return total;
            }
            foreach (char ch in text)
            {
                total = (total * 31 + ch) % 65521;
            }
            return total;
        }

        /// <summary>Wrap a buffer batches index into a fixed-size ring.</summary>
        public static int WrapBufferBatchesIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }

        /// <summary>Sum the decimal digits of a folder id.</summary>
        public static int FolderDigitSum(long n)
        {
            n = n < 0 ? -n : n;
            int total = 0;
            while (n > 0)
            {
                total += (int)(n % 10);
                n /= 10;
            }
            return total;
        }

        /// <summary>Check whether a year is a leap year.</summary>
        public static bool IsLeapYear(int year)
        {
            return (year % 4 == 0 && year % 100 != 0) || year % 400 == 0;
        }

        /// <summary>Clamp a layout value to a valid range.</summary>
        public static double ClampLayout(double value, double lo, double hi)
        {
            if (lo > hi)
            {
                double swap = lo;
                lo = hi;
                hi = swap;
            }
            return Math.Max(lo, Math.Min(hi, value));
        }

        /// <summary>Express a catalog count as a percentage.</summary>
        public static double CatalogPercent(double part, double total)
        {
            if (total == 0.0)
            {
                return 0.0;
            }
            return part * 100.0 / total;
        }
    }
}
