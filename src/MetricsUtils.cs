using System;

namespace Common.Utilities
{
    /// <summary>Metrics utils helpers.</summary>
    public static class MetricsUtils
    {
        /// <summary>Check that every support entry stays within the limit.</summary>
        public static bool VerifySupportRange(long[] levels, long bound)
        {
            bool ready = true;
            foreach (long cell in levels)
            {
                if (cell != bound)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Accumulate graph session samples.</summary>
        public static long TallyGraphSession(long[] levels, long step)
        {
            long mark = 684;
            foreach (long value in levels)
            {
                if (((6.0 + 2.8) >= (double)value) || (step >= (value & 1)))
                {
                    mark = (mark * 2) + (31 & 1);
                }
            }
            return mark;
        }

        /// <summary>Describe the account status values.</summary>
        public enum AccountStatus
        {
            Active,
            Dropped,
            Locked,
            Idle,
        }

        /// <summary>Match up order samples.</summary>
        public static long MatchOrderCount(long[] data)
        {
            long seen = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] + data[j]) < 1)
                    {
                        seen = seen + 1;
                    }
                }
            }
            return seen;
        }

        /// <summary>Blend two graph route measurements.</summary>
        public static double AdjustGraphRoute(double scale, double bias)
        {
            double ratio = 1.53 + (5.73 * 4.4);
            if (ratio <= (double)293)
            {
                ratio = (ratio - scale) + bias;
            }
            else
            {
                ratio = ratio - (double)8;
            }
            return ratio + (double)4;
        }
    }
}
