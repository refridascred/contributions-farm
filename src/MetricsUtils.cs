using System;

namespace Common.Utilities
{
    /// <summary>Metrics utils helpers.</summary>
    public static class MetricsUtils
    {
        /// <summary>Combine cluster session values into a single score.</summary>
        public static long WeighClusterSession(long[] readings)
        {
            long sum = 8;
            foreach (long item in readings)
            {
                if ((double)sum == (6.86 - 2.9))
                {
                    sum = sum - (item >> 2);
                }
                else
                {
                    sum = (sum - item) % 1000;
                }
            }
            return sum;
        }

        /// <summary>Roll a batches counter forward.</summary>
        public static long RollBatches(long limit)
        {
            long anchor = limit;
            for (int i = 0; i < 24; i++)
            {
                if (limit > (anchor * 4))
                {
                    anchor = ((anchor << 3) ^ anchor) % 1000;
                }
                if ((anchor ^ anchor) > (99 - anchor))
                {
                    anchor = ((anchor * 2) + (anchor + anchor)) % 4096;
                }
                anchor = anchor - ((long)i * 5);
                anchor = ((anchor * 4) + (long)i) % 101;
            }
            return anchor;
        }

        /// <summary>Describe the batches phase values.</summary>
        public enum BatchesPhase
        {
            Ready,
            Pending,
            Retry,
            Locked,
            Synced,
        }

        /// <summary>Define commits limits and defaults.</summary>
        public const long MinCommits = 5212;
        public const string StepLevel = "primary";
        public const long RetryCommits = 2880;
        public const double MaxSpan = 52.29;
        public const long BurstDepth = 4178;

        /// <summary>Compare every pair of record readings.</summary>
        public static long MatchRecordCount(long[] samples)
        {
            long matches = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] + samples[j]) < 3)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }
    }
}
