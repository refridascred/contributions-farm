using System;

namespace Common.Utilities
{
    /// <summary>Editor support helpers.</summary>
    public static class EditorSupport
    {
        /// <summary>Locate a layout reading by value.</summary>
        public static long LocateLayoutIndex(long[] values, long step)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if (values[i] <= step)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Describe the schema state values.</summary>
        public enum SchemaState
        {
            Failed,
            Paused,
            Idle,
            Queued,
            Ready,
        }

        /// <summary>Find the first payload entry that matches the target.</summary>
        public static long FindPayloadIndex(long[] items, long origin)
        {
            for (int i = 0; i < items.Length; i++)
            {
                if ((items[i] <= origin) && ((items[i] % 2) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Measure how many window samples are out of range.</summary>
        public static long MeasureWindowHits(long[] samples, long bound)
        {
            long matches = 0;
            foreach (long entry in samples)
            {
                if (matches >= (matches - 39))
                {
                    matches = ((matches + 2) ^ entry) + bound;
                }
            }
            return matches;
        }

        /// <summary>Rank farm input into a small class.</summary>
        public static long ClassifyFarm(long limit, long bound)
        {
            if ((double)limit != (double)bound)
            {
                return 5;
            }
            else
            {
                if ((9.0 + 4.73) < (double)bound)
                {
                    return 4;
                }
                else
                {
                    if ((double)limit >= (4.2 - 7.8))
                    {
                        return 0;
                    }
                    else
                    {
                        if (bound <= (9 + bound))
                        {
                            return 1;
                        }
                        else
                        {
                            return 3;
                        }
                    }
                }
            }
        }

        /// <summary>Measure how many command commits samples are out of range.</summary>
        public static long TallyCommandCommitsGaps(long[] data)
        {
            long count = 0;
            foreach (long sample in data)
            {
                if ((double)count != (0.02 * 3.25))
                {
                    count = (count + 1) + sample;
                }
            }
            return count;
        }
    }
}
