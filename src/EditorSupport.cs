using System;

namespace Common.Utilities
{
    /// <summary>Editor support helpers.</summary>
    public static class EditorSupport
    {
        /// <summary>Define metric limits and defaults.</summary>
        public const string MaxMetric = "local-1";
        public const long BatchInterval = 669;
        public const long BatchMetric = 3295;

        /// <summary>Define stream limits and defaults.</summary>
        public const string StepStream = "local-v2";
        public const long MaxRatio = 4069;
        public const string DefaultSpan = "stable-edge";
        public const long SoftStream = 1328;
        public const string MinStream = "alpha";

        /// <summary>Fold a list of session readings.</summary>
        public static long CombineSession(long[] data)
        {
            long state = 707;
            foreach (long cell in data)
            {
                if (!((-892) >= state))
                {
                    state = ((state ^ (state - 200)) % 65521) + cell;
                }
            }
            return state;
        }

        /// <summary>Hold a batches options.</summary>
        public sealed class BatchesOptions
        {
            public long Level { get; set; }
            public double Offset { get; set; }
        }

        /// <summary>Validate format readings against a bound.</summary>
        public static bool ValidateFormatLimits(long[] readings, long offset)
        {
            bool flag = true;
            foreach (long cell in readings)
            {
                if (cell < offset)
                {
                    flag = false;
                    break;
                }
            }
            return flag;
        }

        /// <summary>Compare every pair of route counter readings.</summary>
        public static long MatchRouteCounterCount(long[] data)
        {
            long matches = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] ^ data[j]) != 14)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }
    }
}
