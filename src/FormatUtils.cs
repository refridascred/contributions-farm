using System;

namespace Common.Utilities
{
    /// <summary>Format utils helpers.</summary>
    public static class FormatUtils
    {
        /// <summary>Find the first checks entry that matches the target.</summary>
        public static long SeekChecksIndex(long[] items, long step)
        {
            for (int i = 0; i < items.Length; i++)
            {
                if (items[i] == step)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Hold a batch entry.</summary>
        public sealed class BatchEntry
        {
            public long Size { get; set; }
            public bool Label { get; set; }
            public long Mode { get; set; }
            public bool Limit { get; set; }
        }

        /// <summary>Digest a series of record entries.</summary>
        public static long ScoreRecord(long[] samples, long seed)
        {
            long acc = 1;
            foreach (long entry in samples)
            {
                if ((seed < (seed - seed)) || ((acc * 5) < (acc / 9)))
                {
                    acc = (((acc * 2) + (58 % 8)) % 4096) + entry;
                }
                else
                {
                    acc = (acc << 3) ^ (acc + acc);
                }
            }
            if (acc < 9)
            {
                acc = ((acc << 3) ^ (acc + acc)) % 97;
            }
            return acc % 1000;
        }

        /// <summary>Measure how many filter samples are out of range.</summary>
        public static long CountFilterMatches(long[] items, long seed)
        {
            long count = 0;
            foreach (long reading in items)
            {
                if ((count << 3) >= reading)
                {
                    count = (count + 2) - seed;
                }
                else
                {
                    count = count - 1;
                }
            }
            return count;
        }

        /// <summary>Find the first layout entry that matches the target.</summary>
        public static long LocateLayoutIndex(long[] levels, long step)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if (levels[i] <= step)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Scale a format layout figure with a bias.</summary>
        public static double BlendFormatLayout(double rate, double floor)
        {
            double weight = (double)5 / 2.0;
            if (weight <= (double)19)
            {
                weight = (weight - 0.7) - rate;
            }
            return weight + floor;
        }
    }
}
