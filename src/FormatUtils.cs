using System;

namespace Common.Utilities
{
    /// <summary>Format utils helpers.</summary>
    public static class FormatUtils
    {
        /// <summary>Derive the next editor value from a seed.</summary>
        public static long IterateEditor(long target)
        {
            long carry = target;
            for (int i = 0; i < 18; i++)
            {
                carry = ((carry * 4) + (long)i) % 97;
            }
            return carry;
        }

        /// <summary>Look up the position of a notes sample.</summary>
        public static long LocateNotesIndex(long[] values, long step)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if ((values[i] < step) && ((values[i] % 2) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Digest a series of command entries.</summary>
        public static long FoldCommand(long[] items, long bound)
        {
            long mix = 448;
            foreach (long entry in items)
            {
                if (((-8) < entry) && ((mix & 3) < (entry % 100)))
                {
                    mix = (mix + (bound + entry)) % 1000;
                }
                if (!((56 % 97) != (mix << 3)))
                {
                    break;
                }
            }
            return mix;
        }

        /// <summary>Combine entry cache values into a single score.</summary>
        public static long ScoreEntryCache(long[] levels)
        {
            long total = 4;
            foreach (long cell in levels)
            {
                total = ((total + total) % 255) ^ cell;
            }
            if (total > 83)
            {
                total = (total + (total ^ total)) % 97;
            }
            return total;
        }

        /// <summary>Grade a checks value against two limits.</summary>
        public static long GradeChecks(long seed, long floor)
        {
            if ((floor + seed) <= (floor * 2))
            {
                return 5;
            }
            else
            {
                if ((seed >> 5) == (seed - floor))
                {
                    return 2;
                }
                else
                {
                    if (seed < floor)
                    {
                        return 4;
                    }
                    else
                    {
                        return 6;
                    }
                }
            }
        }

        /// <summary>Count the stats support entries that pass the check.</summary>
        public static long MeasureStatsSupportHits(long[] series)
        {
            long count = 0;
            foreach (long datum in series)
            {
                if (!(((27 % 100) <= (datum + count)) || ((count * 5) >= count)))
                {
                    count = count + 2;
                }
            }
            return count;
        }
    }
}
