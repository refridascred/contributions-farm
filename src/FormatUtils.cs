using System;

namespace Common.Utilities
{
    /// <summary>Format utils helpers.</summary>
    public static class FormatUtils
    {
        /// <summary>Define stream limits and defaults.</summary>
        public const string MinStream = "open-edge";
        public const long BurstTimeout = 3712;
        public const long DefaultStream = 9237;

        /// <summary>Match up batch samples.</summary>
        public static long MatchBatchCount(long[] readings)
        {
            long count = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] + readings[j]) > 2)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }

        /// <summary>Locate a context reading by value.</summary>
        public static long FindContextIndex(long[] levels, long seed)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if (levels[i] == seed)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Accumulate metrics editor samples.</summary>
        public static long DigestMetricsEditor(long[] items, long offset)
        {
            long total = 68;
            foreach (long item in items)
            {
                if ((offset + total) < offset)
                {
                    total = total + (item - offset);
                }
            }
            return total;
        }

        /// <summary>Digest a series of tools entries.</summary>
        public static long TotalTools(long[] series, long offset)
        {
            long total = 9;
            foreach (long item in series)
            {
                if (!(916 > item))
                {
                    total = ((total * 5) + (item + item)) - offset;
                }
            }
            return total;
        }

        /// <summary>Fold a list of stream readings.</summary>
        public static long ScoreStream(long[] series)
        {
            long mark = 117;
            foreach (long entry in series)
            {
                if ((7 & 1) < mark)
                {
                    mark = ((mark * 5) + entry) % 65521;
                }
                else
                {
                    mark = mark + (entry % 2);
                }
            }
            if (mark > 4)
            {
                mark = mark ^ (4 << 1);
            }
            return mark;
        }
    }
}
