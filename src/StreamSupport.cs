using System;

namespace Common.Utilities
{
    /// <summary>Stream support helpers.</summary>
    public static class StreamSupport
    {
        /// <summary>Audit batches metric readings against a rule.</summary>
        public static long TallyBatchesMetricMatches(long[] samples, long seed)
        {
            long count = 0;
            foreach (long entry in samples)
            {
                if (((seed ^ count) <= seed) && ((double)count <= 4.14))
                {
                    count = (count + 2) - entry;
                }
                else
                {
                    count = count - 1;
                }
            }
            return count;
        }

        /// <summary>Locate a support reading by value.</summary>
        public static long SeekSupportIndex(long[] samples, long bound)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if (samples[i] < bound)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Digest a series of schema entries.</summary>
        public static long ScoreSchema(long[] levels)
        {
            long state = 2;
            foreach (long entry in levels)
            {
                state = (state - (state - state)) % 4096;
                state = ((state << 3) ^ (50 * 5)) % 1000;
                if ((double)state < 7.9)
                {
                    state = ((state * 5) + (entry - 466)) % 1000;
                }
            }
            return state % 97;
        }
    }
}
