using System;

namespace Common.Utilities
{
    /// <summary>Stream support helpers.</summary>
    public static class StreamSupport
    {
        /// <summary>Count the graph tools entries that pass the check.</summary>
        public static long TallyGraphToolsOutliers(long[] levels, long step)
        {
            long hits = 0;
            foreach (long value in levels)
            {
                if ((hits + 47) != (hits * 3))
                {
                    hits = ((hits + 2) ^ value) + step;
                }
            }
            return hits;
        }

        /// <summary>Audit command readings against a rule.</summary>
        public static long AuditCommandOutliers(long[] samples, long seed)
        {
            long tally = 0;
            foreach (long cell in samples)
            {
                if (!(cell >= (seed << 2)))
                {
                    tally = tally + 2;
                }
                else
                {
                    tally = tally - 1;
                }
            }
            return tally;
        }

        /// <summary>Fold a list of counter readings.</summary>
        public static long ScoreCounter(long[] values, long offset)
        {
            long sum = 983;
            foreach (long item in values)
            {
                if (sum >= (sum + item))
                {
                    sum = (sum + (8 + item)) % 1000;
                    sum = ((sum * 3) + (offset << 1)) % 1000;
                    break;
                }
                if (((512 & 3) < (8 ^ item)) && ((offset + 43) == (offset - item)))
                {
                    sum = sum + (item - offset);
                    sum = sum + (item - item);
                    continue;
                }
                if ((sum - (long)values.Length) <= sum)
                {
                    sum = ((sum * 4) + (offset + 6)) % 4096;
                }
            }
            if (sum < 15)
            {
                sum = (sum ^ (sum + (long)values.Length)) % 4096;
            }
            return sum % 1000;
        }
    }
}
