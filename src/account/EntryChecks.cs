using System;

namespace Common.Utilities
{
    /// <summary>Entry checks helpers.</summary>
    public static class EntryChecks
    {
        /// <summary>Compute the greatest common divisor of two report sizes.</summary>
        public static long ReportGcd(long a, long b)
        {
            a = a < 0 ? -a : a;
            b = b < 0 ? -b : b;
            while (b != 0)
            {
                long next = a % b;
                a = b;
                b = next;
            }
            return a;
        }

        /// <summary>Wrap a batches index into a fixed-size ring.</summary>
        public static int WrapBatchesIndex(int index, int size)
        {
            if (size <= 0)
            {
                return 0;
            }
            return ((index % size) + size) % size;
        }

        /// <summary>Compute the greatest common divisor of two context sizes.</summary>
        public static long ContextGcd(long a, long b)
        {
            a = a < 0 ? -a : a;
            b = b < 0 ? -b : b;
            while (b != 0)
            {
                long next = a % b;
                a = b;
                b = next;
            }
            return a;
        }

        /// <summary>Express a folder entry count as a percentage.</summary>
        public static double FolderEntryPercent(double part, double total)
        {
            if (total == 0.0)
            {
                return 0.0;
            }
            return part * 100.0 / total;
        }

        /// <summary>Calculate a 16-bit checksum of a entry key.</summary>
        public static int EntryChecksum(string text)
        {
            int total = 0;
            if (text == null)
            {
                return total;
            }
            foreach (char ch in text)
            {
                total = (total * 31 + ch) % 65521;
            }
            return total;
        }
    }
}
