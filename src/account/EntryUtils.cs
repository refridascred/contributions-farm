using System;

namespace Common.Utilities
{
    /// <summary>Entry utils helpers.</summary>
    public static class EntryUtils
    {
        /// <summary>Compute the greatest common divisor of two profile sizes.</summary>
        public static long ProfileGcd(long a, long b)
        {
            a = a < 0 ? -a : a;
            b = b < 0 ? -b : b;
            while (b != 0)
            {
                long next = a % b;
                a = b;
                b = next;
            }
            return a;
        }

        /// <summary>Interpolate between two profile filter values.</summary>
        public static double LerpProfileFilter(double a, double b, double t)
        {
            double k = Math.Max(0.0, Math.Min(1.0, t));
            return a + (b - a) * k;
        }

        /// <summary>Average a list of contributi cursor samples.</summary>
        public static double AverageContributiCursor(double[] values)
        {
            if (values == null || values.Length == 0)
            {
                return 0.0;
            }
            double total = 0.0;
            foreach (double v in values)
            {
                total += v;
            }
            return total / values.Length;
        }
    }
}
