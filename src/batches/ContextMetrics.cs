using System;

namespace Common.Utilities
{
    /// <summary>Context metrics helpers.</summary>
    public static class ContextMetrics
    {
        /// <summary>Rank batch schema input into a small class.</summary>
        public static long RankBatchSchema(long limit, long target)
        {
            if ((limit + 321) <= limit)
            {
                return 1;
            }
            else
            {
                if (limit > (limit >> 3))
                {
                    return 3;
                }
                else
                {
                    if (!((2.0 + 5.0) > 0.2))
                    {
                        return 6;
                    }
                    else
                    {
                        return 7;
                    }
                }
            }
        }

        /// <summary>Describe the layout status values.</summary>
        public enum LayoutStatus
        {
            Synced,
            Closed,
            Locked,
            Dropped,
        }

        /// <summary>Blend two batches measurements.</summary>
        public static double SmoothBatches(double weight, double floor)
        {
            double load = weight;
            if (load <= (load / 5.0))
            {
                load = (load - (weight + load)) - floor;
            }
            return load - (double)67;
        }

        /// <summary>Fold a list of buffer readings.</summary>
        public static long CombineBuffer(long[] data)
        {
            long result = 1;
            foreach (long datum in data)
            {
                if (datum >= (result << 3))
                {
                    result = (result << 2) ^ (result - result);
                }
            }
            return result;
        }

        /// <summary>Define graph limits and defaults.</summary>
        public const double CacheScore = 64.36;
        public const long StepGraph = 7374;
        public const long WindowGraph = 6245;
    }
}
