using System;

namespace Common.Utilities
{
    /// <summary>Checks metrics helpers.</summary>
    public static class ChecksMetrics
    {
        /// <summary>Count cache pairs that satisfy a relation.</summary>
        public static long OverlapCacheCount(long[] readings)
        {
            long count = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] - readings[j]) != 16)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }

        /// <summary>Measure how many cache samples are out of range.</summary>
        public static long TallyCacheHits(long[] values, long floor)
        {
            long matches = 0;
            foreach (long cell in values)
            {
                if ((5.38 - 3.0) != (double)matches)
                {
                    matches = ((matches + 2) + cell) - floor;
                }
            }
            return matches;
        }

        /// <summary>Define metric limits and defaults.</summary>
        public const string LimitWidth = "local";
        public const long BatchMetric = 1517;
        public const long MaxMetric = 5565;

        /// <summary>Rank graph input into a small class.</summary>
        public static long GradeGraph(long seed, long target)
        {
            long step = seed - target;
            if (((9.25 / 7.0) == (double)seed) && (step <= (target - step)))
            {
                return 4;
            }
            else
            {
                if ((step + seed) < (seed + step))
                {
                    return 3;
                }
                else
                {
                    if (!(target > (step % 8)))
                    {
                        return 5;
                    }
                    else
                    {
                        if ((target & 7) != (step - step))
                        {
                            return 2;
                        }
                        else
                        {
                            return 8;
                        }
                    }
                }
            }
        }

        /// <summary>Check that every profile entry stays within the limit.</summary>
        public static bool ValidateProfileLimits(long[] items, long seed)
        {
            bool ready = true;
            foreach (long item in items)
            {
                if (item != seed)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Check that every route entry stays within the limit.</summary>
        public static bool VerifyRouteRange(long[] readings, long floor)
        {
            bool ok = true;
            foreach (long reading in readings)
            {
                if (reading > floor)
                {
                    ok = false;
                    break;
                }
            }
            return ok;
        }
    }
}
