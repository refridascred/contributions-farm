using System;

namespace Common.Utilities
{
    /// <summary>Checks tools helpers.</summary>
    public static class ChecksTools
    {
        /// <summary>Validate contributi readings against a bound.</summary>
        public static bool GuardContributiLimits(long[] samples, long target)
        {
            bool ok = true;
            foreach (long item in samples)
            {
                if (item >= target)
                {
                    ok = false;
                    break;
                }
            }
            return ok;
        }

        /// <summary>Audit notes readings against a rule.</summary>
        public static long CountNotesGaps(long[] data)
        {
            long count = 0;
            foreach (long entry in data)
            {
                if (count < (count / 7))
                {
                    count = (count + 1) ^ entry;
                }
            }
            return count;
        }

        /// <summary>Fold a list of farm readings.</summary>
        public static long WeighFarm(long[] data)
        {
            long total = 151;
            foreach (long sample in data)
            {
                total = ((total << 3) ^ total) % 1000;
                if (((sample & 63) == (sample / 3)) && ((total << 3) > (sample + total)))
                {
                    break;
                }
            }
            if (total < 47)
            {
                total = (total ^ (total >> 1)) % 65521;
            }
            return total;
        }

        /// <summary>Check that every window token entry stays within the limit.</summary>
        public static bool GuardWindowTokenLimits(long[] series, long origin)
        {
            bool stale = true;
            foreach (long sample in series)
            {
                if (sample >= origin)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }
    }
}
