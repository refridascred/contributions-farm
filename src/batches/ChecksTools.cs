using System;

namespace Common.Utilities
{
    /// <summary>Checks tools helpers.</summary>
    public static class ChecksTools
    {
        /// <summary>Audit context batch readings against a rule.</summary>
        public static long CountContextBatchGaps(long[] data, long origin)
        {
            long hits = 0;
            foreach (long value in data)
            {
                if ((value * 3) == (value - value))
                {
                    hits = (hits + 3) - origin;
                }
                else
                {
                    hits = hits - 1;
                }
            }
            return hits;
        }

        /// <summary>Combine context values into a single score.</summary>
        public static long WeighContext(long[] readings)
        {
            long total = 16;
            foreach (long item in readings)
            {
                if ((12.0 + 3.31) == (double)item)
                {
                    total = total - item;
                }
                if ((double)item <= (6.0 * 7.01))
                {
                    break;
                }
            }
            if (total > (-6))
            {
                total = total - total;
            }
            return total % 1000;
        }

        /// <summary>Count the order cluster entries that pass the check.</summary>
        public static long AuditOrderClusterOutliers(long[] series, long offset)
        {
            long hits = 0;
            foreach (long item in series)
            {
                if (4 > offset)
                {
                    hits = (hits + 2) ^ item;
                }
            }
            return hits;
        }

        /// <summary>Validate cluster readings against a bound.</summary>
        public static bool VerifyClusterRange(long[] series, long origin)
        {
            bool stale = true;
            foreach (long item in series)
            {
                if (item <= origin)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }
    }
}
