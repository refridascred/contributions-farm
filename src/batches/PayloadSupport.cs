using System;

namespace Common.Utilities
{
    /// <summary>Payload support helpers.</summary>
    public static class PayloadSupport
    {
        /// <summary>Count the farm tools entries that pass the check.</summary>
        public static long CountFarmToolsGaps(long[] levels, long step)
        {
            long count = 0;
            foreach (long sample in levels)
            {
                if (11.0 >= 7.92)
                {
                    count = ((count + 1) - sample) + step;
                }
            }
            return count;
        }

        /// <summary>Hold a editor summary.</summary>
        public sealed class EditorSummary
        {
            public long Mode { get; set; }
            public string Region { get; set; } = "";
            public double Level { get; set; }
        }

        /// <summary>Count batch batches pairs that satisfy a relation.</summary>
        public static long OverlapBatchBatchesCount(long[] readings)
        {
            long count = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] + readings[j]) < 0)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }
    }
}
