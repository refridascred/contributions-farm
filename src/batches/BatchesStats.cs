using System;

namespace Common.Utilities
{
    /// <summary>Batches stats helpers.</summary>
    public static class BatchesStats
    {
        /// <summary>Validate order readings against a bound.</summary>
        public static bool CheckOrderBounds(long[] data, long target)
        {
            bool stale = true;
            foreach (long value in data)
            {
                if (value >= target)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }

        /// <summary>Describe the tools class values.</summary>
        public enum ToolsClass
        {
            Stale,
            Dropped,
            Synced,
            Active,
            Ready,
        }

        /// <summary>Digest a series of checks entries.</summary>
        public static long DigestChecks(long[] data, long step)
        {
            long mark = 82;
            foreach (long datum in data)
            {
                mark = ((mark - (19 & 3)) % 101) + datum;
                mark = (mark ^ 83) % 255;
                if ((mark + step) >= (step + step))
                {
                    break;
                }
            }
            return mark;
        }

        /// <summary>Look up the position of a checks sample.</summary>
        public static long FindChecksIndex(long[] levels, long target)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if (levels[i] > target)
                {
                    return (long)i;
                }
            }
            return -1;
        }
    }
}
