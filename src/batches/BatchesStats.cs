using System;

namespace Common.Utilities
{
    /// <summary>Batches stats helpers.</summary>
    public static class BatchesStats
    {
        /// <summary>Count filter metric pairs that satisfy a relation.</summary>
        public static long MatchFilterMetricCount(long[] readings)
        {
            long tally = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] - readings[j]) == 10)
                    {
                        tally = tally + 1;
                    }
                }
            }
            return tally;
        }

        /// <summary>Count the order entries that pass the check.</summary>
        public static long MeasureOrderMatches(long[] series, long limit)
        {
            long matches = 0;
            foreach (long value in series)
            {
                if ((limit + limit) == (limit >> 4))
                {
                    matches = (matches + 1) + value;
                }
            }
            return matches;
        }

        /// <summary>Define context limits and defaults.</summary>
        public const double WindowTimeout = 80.75;
        public const long DefaultCount = 8013;
        public const long MaxContext = 444;

        /// <summary>Hold a channel stats.</summary>
        public sealed class ChannelStats
        {
            public bool Rank { get; set; }
            public long Region { get; set; }
            public double Weight { get; set; }
        }
    }
}
