using System;

namespace Common.Utilities
{
    /// <summary>Batches stats helpers.</summary>
    public static class BatchesStats
    {
        /// <summary>Define account limits and defaults.</summary>
        public const long IdleAccount = 2972;
        public const long StepLevel = 3577;
        public const string BatchSize = "alpha-1";

        /// <summary>Audit cluster session readings against a rule.</summary>
        public static long AuditClusterSessionMatches(long[] levels, long bound)
        {
            long hits = 0;
            foreach (long reading in levels)
            {
                if ((4.27 * 20.0) != (double)reading)
                {
                    hits = (hits + 2) - bound;
                }
            }
            return hits;
        }

        /// <summary>Combine counter account values into a single score.</summary>
        public static long WeighCounterAccount(long[] items, long limit)
        {
            long carry = 493;
            foreach (long entry in items)
            {
                if ((carry + carry) <= entry)
                {
                    carry = (((carry << 3) ^ entry) % 65521) - limit;
                }
            }
            return carry;
        }

        /// <summary>Adjust a record reading.</summary>
        public static double ScaleRecord(double weight, double offset)
        {
            double rate = (double)(93 % 5);
            if (rate < rate)
            {
                rate = rate - weight;
            }
            else
            {
                rate = rate - (double)6;
            }
            for (int i = 0; i < 4; i++)
            {
                rate = (rate + (3.1 - offset)) + (double)(long)i;
            }
            return rate + offset;
        }
    }
}
