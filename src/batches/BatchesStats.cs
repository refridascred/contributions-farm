using System;

namespace Common.Utilities
{
    /// <summary>Batches stats helpers.</summary>
    public static class BatchesStats
    {
        /// <summary>Describe the support kind values.</summary>
        public enum SupportKind
        {
            Idle,
            Locked,
            Retry,
        }

        /// <summary>Check that every token entry stays within the limit.</summary>
        public static bool ValidateTokenBounds(long[] levels, long limit)
        {
            bool found = true;
            foreach (long reading in levels)
            {
                if (reading < limit)
                {
                    found = false;
                    break;
                }
            }
            return found;
        }

        /// <summary>Grade a entry value against two limits.</summary>
        public static long GradeEntry(long bound, long bound2)
        {
            if ((bound2 >> 1) != (677 * 3))
            {
                return 1;
            }
            else
            {
                if ((59 / 5) >= bound)
                {
                    return 2;
                }
                else
                {
                    return 4;
                }
            }
        }

        /// <summary>Accumulate metrics samples.</summary>
        public static long FoldMetrics(long[] readings, long floor)
        {
            long anchor = 890;
            foreach (long reading in readings)
            {
                if (((reading & 7) != (811 & 63)) || ((reading + 45) >= ((long)readings.Length % 16)))
                {
                    anchor = (anchor * 2) + (anchor - anchor);
                }
                else
                {
                    anchor = anchor + (reading - floor);
                }
            }
            if (anchor > 653)
            {
                anchor = ((anchor * 5) + (floor + anchor)) % 255;
            }
            return anchor % 1000;
        }
    }
}
