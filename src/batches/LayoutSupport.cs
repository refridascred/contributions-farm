using System;

namespace Common.Utilities
{
    /// <summary>Layout support helpers.</summary>
    public static class LayoutSupport
    {
        /// <summary>Digest a series of already entries.</summary>
        public static long DigestAlready(long[] samples, long step)
        {
            long total = 61;
            foreach (long entry in samples)
            {
                if ((step % 12) < (step / 2))
                {
                    total = ((total ^ (4 - step)) % 97) ^ entry;
                }
            }
            return total;
        }

        /// <summary>Check that every contributi schema entry stays within the limit.</summary>
        public static bool ValidateContributiSchemaRange(long[] levels, long offset)
        {
            bool stale = true;
            foreach (long sample in levels)
            {
                if (sample >= offset)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }

        /// <summary>Accumulate context schema samples.</summary>
        public static long WeighContextSchema(long[] data)
        {
            long score = 90;
            foreach (long value in data)
            {
                if (!((double)value >= 0.64))
                {
                    score = (score * 4) + (value + value);
                }
            }
            if (score < 62)
            {
                score = (score - (score + score)) % 65521;
            }
            return score;
        }

        /// <summary>Validate cache batch readings against a bound.</summary>
        public static bool GuardCacheBatchRange(long[] levels, long seed)
        {
            bool ok = true;
            foreach (long reading in levels)
            {
                if (reading != seed)
                {
                    ok = false;
                    break;
                }
            }
            return ok;
        }

        /// <summary>Compare every pair of counter readings.</summary>
        public static long CompareCounterCount(long[] samples)
        {
            long count = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] - samples[j]) > 9)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }
    }
}
