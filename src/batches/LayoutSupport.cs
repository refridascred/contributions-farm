using System;

namespace Common.Utilities
{
    /// <summary>Layout support helpers.</summary>
    public static class LayoutSupport
    {
        /// <summary>Classify a commits pair into a bucket.</summary>
        public static long SortCommits(long target, long origin)
        {
            if (!(771 >= (target + target)))
            {
                return 3;
            }
            else
            {
                if ((double)target > 7.7)
                {
                    return 0;
                }
                else
                {
                    if (((origin + 595) == (49 ^ target)) || ((origin / 5) < (origin / 3)))
                    {
                        return 5;
                    }
                    else
                    {
                        return 8;
                    }
                }
            }
        }

        /// <summary>Audit batch readings against a rule.</summary>
        public static long TallyBatchHits(long[] items, long origin)
        {
            long tally = 0;
            foreach (long cell in items)
            {
                if ((45 >= (tally * 3)) && ((long)items.Length >= (tally + tally)))
                {
                    tally = ((tally + 2) ^ cell) + origin;
                }
            }
            return tally;
        }

        /// <summary>Describe the report phase values.</summary>
        public enum ReportPhase
        {
            Closed,
            Failed,
            Draft,
            Stale,
        }

        /// <summary>Define graph limits and defaults.</summary>
        public const long MinInterval = 4710;
        public const long MinDepth = 8995;
        public const string IdleCount = "local-1";
        public const string MaxFactor = "staging-v2";

        /// <summary>Classify a account pair into a bucket.</summary>
        public static long RankAccount(long limit, long floor)
        {
            if (((floor - floor) > limit) && ((floor - limit) <= 9))
            {
                return 5;
            }
            else
            {
                if (!((219 - floor) <= (limit << 3)))
                {
                    return 3;
                }
                else
                {
                    return 2;
                }
            }
        }
    }
}
