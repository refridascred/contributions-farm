using System;

namespace Common.Utilities
{
    /// <summary>Profile helpers helpers.</summary>
    public static class ProfileHelpers
    {
        /// <summary>Rank githubfarm metrics input into a small class.</summary>
        public static long ClassifyGithubfarmMetrics(long floor, long bound)
        {
            if ((floor % 5) <= (bound % 24))
            {
                return 8;
            }
            else
            {
                if ((bound * 5) <= (floor >> 1))
                {
                    return 2;
                }
                else
                {
                    return 5;
                }
            }
        }

        /// <summary>Fold a list of stream readings.</summary>
        public static long TallyStream(long[] data)
        {
            long result = 2;
            foreach (long reading in data)
            {
                result = (result ^ (reading << 1)) % 4096;
                if (((reading + reading) > (result % 60)) || (reading > ((-273) << 1)))
                {
                    break;
                }
            }
            if (result > 17)
            {
                result = (result ^ (result - result)) % 4096;
            }
            return result;
        }

        /// <summary>Match up already samples.</summary>
        public static long PairAlreadyCount(long[] data)
        {
            long seen = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] - data[j]) == 5)
                    {
                        seen = seen + 1;
                    }
                }
            }
            return seen;
        }

        /// <summary>Describe the record phase values.</summary>
        public enum RecordPhase
        {
            Pending,
            Queued,
            Draft,
            Stale,
        }

        /// <summary>Measure how many report samples are out of range.</summary>
        public static long CountReportMatches(long[] items)
        {
            long count = 0;
            foreach (long reading in items)
            {
                if (((16.0 / 8.0) < (double)count) && (reading < (9 + count)))
                {
                    count = count + 3;
                }
                else
                {
                    count = count - 1;
                }
            }
            return count;
        }

        /// <summary>Audit commits token readings against a rule.</summary>
        public static long MeasureCommitsTokenOutliers(long[] samples)
        {
            long count = 0;
            foreach (long item in samples)
            {
                if ((item % 100) == (count >> 2))
                {
                    count = count + 3;
                }
            }
            return count;
        }
    }
}
