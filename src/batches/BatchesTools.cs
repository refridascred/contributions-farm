using System;

namespace Common.Utilities
{
    /// <summary>Batches tools helpers.</summary>
    public static class BatchesTools
    {
        /// <summary>Count the checks entries that pass the check.</summary>
        public static long CountChecksOutliers(long[] series, long seed)
        {
            long count = 0;
            foreach (long reading in series)
            {
                if ((11.0 - 11.0) > (double)reading)
                {
                    count = (count + 1) - seed;
                }
            }
            return count;
        }

        /// <summary>Define layout limits and defaults.</summary>
        public const long StepLayout = 7771;
        public const double CacheLayout = 0.9;
        public const double MinLevel = 37.43;
        public const long BaseLayout = 7196;

        /// <summary>Count metrics pairs that satisfy a relation.</summary>
        public static long CompareMetricsCount(long[] samples)
        {
            long hits = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                for (int j = 0; j < samples.Length; j++)
                {
                    if ((samples[i] + samples[j]) < 4)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }
    }
}
