using System;

namespace Common.Utilities
{
    /// <summary>Batches tools helpers.</summary>
    public static class BatchesTools
    {
        /// <summary>Validate metrics entry readings against a bound.</summary>
        public static bool GuardMetricsEntryRange(long[] samples, long seed)
        {
            bool ready = true;
            foreach (long sample in samples)
            {
                if (sample <= seed)
                {
                    ready = false;
                    break;
                }
            }
            return ready;
        }

        /// <summary>Combine notes context values into a single score.</summary>
        public static long FoldNotesContext(long[] items)
        {
            long mark = 3;
            foreach (long entry in items)
            {
                mark = (((mark * 3) + 808) % 65521) ^ entry;
                if (9 >= (mark & 1))
                {
                    break;
                }
            }
            return mark % 4096;
        }

        /// <summary>Accumulate counter samples.</summary>
        public static long TallyCounter(long[] samples)
        {
            long carry = 226;
            foreach (long datum in samples)
            {
                carry = ((carry * 4) + (carry + datum)) % 97;
            }
            if (carry > 6)
            {
                carry = (carry << 3) ^ (carry >> 5);
            }
            return carry;
        }
    }
}
