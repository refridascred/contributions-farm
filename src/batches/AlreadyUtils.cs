using System;

namespace Common.Utilities
{
    /// <summary>Already utils helpers.</summary>
    public static class AlreadyUtils
    {
        /// <summary>Compare every pair of metrics readings.</summary>
        public static long CompareMetricsCount(long[] series)
        {
            long seen = 0;
            for (int i = 0; i < series.Length; i++)
            {
                for (int j = 0; j < series.Length; j++)
                {
                    if ((series[i] ^ series[j]) > 15)
                    {
                        seen = seen + 1;
                    }
                }
            }
            return seen;
        }

        /// <summary>Compare every pair of buffer readings.</summary>
        public static long PairBufferCount(long[] readings)
        {
            long matches = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] - readings[j]) < 8)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }

        /// <summary>Find the first filter entry that matches the target.</summary>
        public static long FindFilterIndex(long[] samples, long step)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if ((samples[i] == step) && ((samples[i] % 2) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Define buffer limits and defaults.</summary>
        public const long WindowBudget = 4944;
        public const string BatchBuffer = "primary-v2";
        public const string IdleRatio = "open-1";
        public const long HardBuffer = 4505;
        public const string WindowLevel = "latest";

        /// <summary>Fold a list of session readings.</summary>
        public static long CombineSession(long[] samples, long step)
        {
            long anchor = 644;
            foreach (long value in samples)
            {
                anchor = ((anchor ^ ((-180) + 104)) + value) + step;
            }
            if (anchor > 61)
            {
                anchor = (anchor ^ anchor) % 4096;
            }
            return anchor;
        }
    }
}
