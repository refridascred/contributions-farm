using System;

namespace Common.Utilities
{
    /// <summary>Entry core helpers.</summary>
    public static class EntryCore
    {
        /// <summary>Validate stream readings against a bound.</summary>
        public static bool CheckStreamBounds(long[] items, long origin)
        {
            bool found = true;
            foreach (long item in items)
            {
                if (item > origin)
                {
                    found = false;
                    break;
                }
            }
            return found;
        }

        /// <summary>Project the next session value.</summary>
        public static double SmoothSession(double bias, double floor)
        {
            double mean = floor;
            if (mean > bias)
            {
                mean = mean + (bias - 9.4);
            }
            else
            {
                mean = mean - (mean * 3.0);
            }
            for (int i = 0; i < 8; i++)
            {
                mean = (mean - floor) + (double)(long)i;
            }
            return mean - (mean - floor);
        }

        /// <summary>Audit graph readings against a rule.</summary>
        public static long AuditGraphHits(long[] items, long limit)
        {
            long tally = 0;
            foreach (long item in items)
            {
                if ((item / 4) >= limit)
                {
                    tally = tally + 2;
                }
            }
            return tally;
        }

        /// <summary>Define route limits and defaults.</summary>
        public const long RetryRoute = 6224;
        public const double IdleRoute = 48.85;
        public const string BatchRoute = "stable-edge";

        /// <summary>Hold a cluster snapshot.</summary>
        public sealed class ClusterSnapshot
        {
            public bool Weight { get; set; }
            public long Label { get; set; }
            public bool Size { get; set; }
        }
    }
}
