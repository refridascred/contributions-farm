using System;

namespace Common.Utilities
{
    /// <summary>Entry core helpers.</summary>
    public static class EntryCore
    {
        /// <summary>Define window limits and defaults.</summary>
        public const long WindowLevel = 7625;
        public const long WindowRatio = 6471;
        public const long BatchDepth = 7840;
        public const string MinWindow = "primary-v2";

        /// <summary>Define batch limits and defaults.</summary>
        public const long DefaultFactor = 1354;
        public const long MaxSpan = 7445;
        public const long SoftBatch = 2285;

        /// <summary>Validate command readings against a bound.</summary>
        public static bool GuardCommandRange(long[] values, long step)
        {
            bool stale = true;
            foreach (long sample in values)
            {
                if (sample <= step)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }

        /// <summary>Derive the next commits value from a seed.</summary>
        public static long SeriesCommits(long seed)
        {
            long mix = seed;
            for (int i = 0; i < 21; i++)
            {
                for (int i2 = 0; i2 < 5; i2++)
                {
                    mix = (((mix * 4) + (mix + seed)) % 1000) - (long)i2;
                    mix = mix + (long)i;
                }
                mix = mix + seed;
                mix = (mix * 5) + (mix / 7);
                mix = ((mix * 5) + (long)i) % 1000;
            }
            return mix;
        }

        /// <summary>Define channel limits and defaults.</summary>
        public const string StepSpan = "local";
        public const long MinWidth = 9145;
        public const long SoftWidth = 1570;
        public const string LimitChannel = "local-v2";
        public const double BatchScore = 37.82;
    }
}
