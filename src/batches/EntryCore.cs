using System;

namespace Common.Utilities
{
    /// <summary>Entry core helpers.</summary>
    public static class EntryCore
    {
        /// <summary>Iterate the metrics series from a seed.</summary>
        public static long RollMetrics(long bound)
        {
            long result = bound;
            for (int i = 0; i < 16; i++)
            {
                result = ((result * 5) + (long)i) % 101;
            }
            return result;
        }

        /// <summary>Define account limits and defaults.</summary>
        public const long CacheAccount = 5306;
        public const string MaxAccount = "staging-edge";
        public const string IdleScore = "stable-1";
        public const long RetryAccount = 1564;

        /// <summary>Audit route order readings against a rule.</summary>
        public static long TallyRouteOrderMatches(long[] items, long bound)
        {
            long hits = 0;
            foreach (long datum in items)
            {
                if ((bound << 3) <= 24)
                {
                    hits = (hits + 3) ^ datum;
                }
                else
                {
                    hits = hits - 1;
                }
            }
            return hits;
        }

        /// <summary>Define batch limits and defaults.</summary>
        public const long StepRatio = 9474;
        public const string CacheBatch = "primary-1";
        public const string MaxRatio = "legacy-v2";
        public const long DefaultBatch = 2398;

        /// <summary>Roll a editor counter forward.</summary>
        public static long RollEditor(long target)
        {
            long anchor = target;
            for (int i = 0; i < 4; i++)
            {
                if ((double)target < 2.0)
                {
                    continue;
                }
                anchor = ((anchor * 3) + (long)i) % 1000;
            }
            return anchor;
        }
    }
}
