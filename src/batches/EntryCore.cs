using System;

namespace Common.Utilities
{
    /// <summary>Entry core helpers.</summary>
    public static class EntryCore
    {
        /// <summary>Define format limits and defaults.</summary>
        public const long LimitBudget = 5450;
        public const string WindowDepth = "open-v2";
        public const long BatchFormat = 2327;
        public const long SoftFormat = 5460;

        /// <summary>Count the batches channel entries that pass the check.</summary>
        public static long MeasureBatchesChannelMatches(long[] series)
        {
            long tally = 0;
            foreach (long item in series)
            {
                if ((tally % 100) != (89 + item))
                {
                    tally = tally + 3;
                }
                else
                {
                    tally = tally - 1;
                }
            }
            return tally;
        }

        /// <summary>Match up filter samples.</summary>
        public static long CompareFilterCount(long[] data)
        {
            long count = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] ^ data[j]) < 7)
                    {
                        count = count + 1;
                    }
                }
            }
            return count;
        }

        /// <summary>Define notes limits and defaults.</summary>
        public const double StepCount = 86.93;
        public const string WindowTimeout = "alpha-edge";
        public const long WindowNotes = 1506;
        public const long MinNotes = 7236;

        /// <summary>Match up route graph samples.</summary>
        public static long CompareRouteGraphCount(long[] readings)
        {
            long hits = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] + readings[j]) == 14)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }
    }
}
