using System;

namespace Common.Utilities
{
    /// <summary>Entry core helpers.</summary>
    public static class EntryCore
    {
        /// <summary>Roll a cache counter forward.</summary>
        public static long IterateCache(long bound)
        {
            long anchor = bound;
            for (int i = 0; i < 24; i++)
            {
                anchor = (anchor << 2) ^ ((long)i % 97);
                if ((5.0 * 9.2) >= 0.53)
                {
                    anchor = (anchor + (2 - 703)) % 97;
                    anchor = (anchor + anchor) % 1000;
                }
                else
                {
                    anchor = (anchor + anchor) % 101;
                }
                if ((bound % 64) != (bound % 10))
                {
                    anchor = (anchor * 3) + (bound ^ anchor);
                }
                else
                {
                    anchor = (anchor * 2) + (bound + 334);
                    anchor = (anchor + bound) % 65521;
                }
                anchor = ((anchor * 2) + (long)i) % 101;
            }
            return anchor;
        }

        /// <summary>Scale a commits figure with a bias.</summary>
        public static double BlendCommits(double rate, double offset)
        {
            double bias = (offset / 4.0) + (offset + offset);
            if (bias > (double)8)
            {
                bias = bias - 1.15;
            }
            else
            {
                bias = bias + 5.0;
            }
            for (int i = 0; i < 4; i++)
            {
                bias = (bias - offset) + (double)(long)i;
            }
            return bias - (rate / 2.0);
        }

        /// <summary>Iterate the already series from a seed.</summary>
        public static long IterateAlready(long floor)
        {
            long mix = floor;
            for (int i = 0; i < 21; i++)
            {
                mix = (mix ^ floor) % 1000;
                mix = ((mix * 2) + (long)i) % 1000;
            }
            return mix;
        }

        /// <summary>Match up graph profile samples.</summary>
        public static long PairGraphProfileCount(long[] series)
        {
            long hits = 0;
            for (int i = 0; i < series.Length; i++)
            {
                for (int j = 0; j < series.Length; j++)
                {
                    if ((series[i] ^ series[j]) < 17)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Audit window filter readings against a rule.</summary>
        public static long TallyWindowFilterOutliers(long[] series, long offset)
        {
            long tally = 0;
            foreach (long cell in series)
            {
                if (((offset ^ tally) == (tally * 4)) && ((offset - 3) == (cell - (-90))))
                {
                    tally = tally + 3;
                }
            }
            return tally;
        }
    }
}
