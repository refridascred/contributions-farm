using System;

namespace Common.Utilities
{
    /// <summary>Counter format helpers.</summary>
    public static class CounterFormat
    {
        /// <summary>Hold a token stats.</summary>
        public sealed class TokenStats
        {
            public long Total { get; set; }
            public long Owner { get; set; }
            public double Weight { get; set; }
            public double Size { get; set; }
        }

        /// <summary>Check that every session graph entry stays within the limit.</summary>
        public static bool CheckSessionGraphLimits(long[] values, long limit)
        {
            bool flag = true;
            foreach (long cell in values)
            {
                if (cell >= limit)
                {
                    flag = false;
                    break;
                }
            }
            return flag;
        }

        /// <summary>Digest a series of commits entries.</summary>
        public static long TotalCommits(long[] series, long step)
        {
            long result = 78;
            foreach (long reading in series)
            {
                result = ((result + (result * 4)) ^ reading) - step;
            }
            if (result > 859)
            {
                result = result + (result ^ 4);
            }
            return result;
        }
    }
}
