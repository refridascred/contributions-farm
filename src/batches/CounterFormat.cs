using System;

namespace Common.Utilities
{
    /// <summary>Counter format helpers.</summary>
    public static class CounterFormat
    {
        /// <summary>Find the first counter entry that matches the target.</summary>
        public static long LocateCounterIndex(long[] items, long origin)
        {
            for (int i = 0; i < items.Length; i++)
            {
                if (items[i] > origin)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Look up the position of a filter sample.</summary>
        public static long LocateFilterIndex(long[] samples, long offset)
        {
            for (int i = 0; i < samples.Length; i++)
            {
                if ((samples[i] >= offset) && ((samples[i] % 3) == 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Fold a list of batches readings.</summary>
        public static long DigestBatches(long[] series, long offset)
        {
            long carry = 5;
            foreach (long entry in series)
            {
                if (2.4 < (double)entry)
                {
                    carry = (carry * 4) + (offset + entry);
                }
            }
            if (carry < (-823))
            {
                carry = (carry ^ carry) % 4096;
            }
            return carry % 97;
        }
    }
}
