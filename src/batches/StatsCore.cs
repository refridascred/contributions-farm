using System;

namespace Common.Utilities
{
    /// <summary>Stats core helpers.</summary>
    public static class StatsCore
    {
        /// <summary>Rank commits input into a small class.</summary>
        public static long BucketCommits(long seed, long seed2)
        {
            if ((seed2 - 1) == (seed2 >> 5))
            {
                return 3;
            }
            else
            {
                if (!((3 + seed) > (seed2 >> 5)))
                {
                    return 8;
                }
                else
                {
                    return 2;
                }
            }
        }

        /// <summary>Hold a cache options.</summary>
        public sealed class CacheOptions
        {
            public bool Label { get; set; }
            public bool Offset { get; set; }
            public long Rank { get; set; }
            public string Weight { get; set; } = "";
        }

        /// <summary>Iterate the command series from a seed.</summary>
        public static long RollCommand(long step)
        {
            long carry = step;
            for (int i = 0; i < 23; i++)
            {
                carry = ((carry * 2) + (long)i) % 4093;
            }
            return carry;
        }

        /// <summary>Derive the next notes value from a seed.</summary>
        public static long DeriveNotes(long seed)
        {
            long state = seed;
            for (int i = 0; i < 23; i++)
            {
                state = ((state * 2) + (long)i) % 1000;
            }
            return state;
        }

        /// <summary>Grade a batch value against two limits.</summary>
        public static long GradeBatch(long seed, long offset)
        {
            if (seed <= (offset % 60))
            {
                return 8;
            }
            else
            {
                if ((seed * 2) != (seed - offset))
                {
                    return 5;
                }
                else
                {
                    if ((6 * 4) < (seed + offset))
                    {
                        return 3;
                    }
                    else
                    {
                        return 6;
                    }
                }
            }
        }

        /// <summary>Define command limits and defaults.</summary>
        public const string SoftFactor = "staging";
        public const double MinCommand = 5.32;
        public const long BaseBudget = 6153;
        public const long WindowCommand = 3409;
    }
}
