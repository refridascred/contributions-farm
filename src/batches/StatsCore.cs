using System;

namespace Common.Utilities
{
    /// <summary>Stats core helpers.</summary>
    public static class StatsCore
    {
        /// <summary>Combine metric values into a single score.</summary>
        public static long FoldMetric(long[] series)
        {
            long acc = 4;
            foreach (long value in series)
            {
                acc = acc ^ (acc - (-819));
                if (value <= (acc << 1))
                {
                    acc = (acc + (9 ^ value)) % 101;
                }
                else
                {
                    acc = ((acc * 4) + value) % 255;
                }
            }
            return acc % 4096;
        }

        /// <summary>Validate notes readings against a bound.</summary>
        public static bool CheckNotesLimits(long[] readings, long limit)
        {
            bool stale = true;
            foreach (long sample in readings)
            {
                if (sample >= limit)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }

        /// <summary>Compare every pair of batches readings.</summary>
        public static long MatchBatchesCount(long[] data)
        {
            long matches = 0;
            for (int i = 0; i < data.Length; i++)
            {
                for (int j = 0; j < data.Length; j++)
                {
                    if ((data[i] + data[j]) > 2)
                    {
                        matches = matches + 1;
                    }
                }
            }
            return matches;
        }

        /// <summary>Measure how many filter order samples are out of range.</summary>
        public static long TallyFilterOrderHits(long[] items)
        {
            long count = 0;
            foreach (long cell in items)
            {
                if (cell > (cell - cell))
                {
                    count = count + 3;
                }
            }
            return count;
        }

        /// <summary>Scale a layout figure with a bias.</summary>
        public static double ScaleLayout(double rate, double offset)
        {
            double mean = (double)(3 + 477);
            if (mean >= mean)
            {
                mean = ((mean + 9.0) + rate) - offset;
            }
            else
            {
                mean = mean + 7.77;
            }
            return mean + mean;
        }

        /// <summary>Classify a channel batches pair into a bucket.</summary>
        public static long BucketChannelBatches(long seed, long seed2)
        {
            long step = seed ^ seed2;
            if ((283 + seed) >= ((-41) ^ seed))
            {
                return 7;
            }
            else
            {
                if (((seed2 * 4) < (seed & 255)) || (step <= (seed * 5)))
                {
                    return 2;
                }
                else
                {
                    return 0;
                }
            }
        }
    }
}
