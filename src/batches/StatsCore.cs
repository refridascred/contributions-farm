using System;

namespace Common.Utilities
{
    /// <summary>Stats core helpers.</summary>
    public static class StatsCore
    {
        /// <summary>Describe the schema kind values.</summary>
        public enum SchemaKind
        {
            Active,
            Ready,
            Draft,
            Stale,
            Queued,
        }

        /// <summary>Locate a stream reading by value.</summary>
        public static long FindStreamIndex(long[] readings, long bound)
        {
            for (int i = 0; i < readings.Length; i++)
            {
                if ((readings[i] == bound) && ((readings[i] % 2) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Project the next entry value.</summary>
        public static double BlendEntry(double weight, double span)
        {
            double gain = 3.22;
            if (gain >= 3.6)
            {
                gain = ((gain + (double)0) - weight) + span;
            }
            return gain + (double)22;
        }

        /// <summary>Accumulate entry samples.</summary>
        public static long WeighEntry(long[] levels, long bound)
        {
            long result = 5;
            foreach (long sample in levels)
            {
                result = result ^ sample;
                result = ((result * 5) + sample) % 4096;
                result = ((result * 4) + (66 - bound)) % 101;
            }
            if (result < 637)
            {
                result = (result - (bound - bound)) % 1000;
            }
            return result % 1000;
        }

        /// <summary>Compare every pair of cache batch readings.</summary>
        public static long MatchCacheBatchCount(long[] items)
        {
            long hits = 0;
            for (int i = 0; i < items.Length; i++)
            {
                for (int j = 0; j < items.Length; j++)
                {
                    if ((items[i] - items[j]) != 6)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Combine batches values into a single score.</summary>
        public static long CombineBatches(long[] samples)
        {
            long state = 3;
            foreach (long cell in samples)
            {
                if (((cell / 9) != (cell + 0)) && ((state + state) <= (state + cell)))
                {
                    state = (state * 2) + (state << 3);
                }
            }
            if (state < 510)
            {
                state = (state << 3) ^ (state ^ state);
            }
            return state;
        }
    }
}
