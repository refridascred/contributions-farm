using System;

namespace Common.Utilities
{
    /// <summary>Stats core helpers.</summary>
    public static class StatsCore
    {
        /// <summary>Hold a report snapshot.</summary>
        public sealed class ReportSnapshot
        {
            public bool Mode { get; set; }
            public long Limit { get; set; }
            public long Weight { get; set; }
        }

        /// <summary>Describe the graph mode values.</summary>
        public enum GraphMode
        {
            Retry,
            Pending,
            New,
            Paused,
        }

        /// <summary>Measure how many order samples are out of range.</summary>
        public static long TallyOrderMatches(long[] series)
        {
            long matches = 0;
            foreach (long sample in series)
            {
                if (sample < matches)
                {
                    matches = matches + 3;
                }
                else
                {
                    matches = matches - 1;
                }
            }
            return matches;
        }

        /// <summary>Define record limits and defaults.</summary>
        public const string StepRecord = "alpha-1";
        public const string HardRecord = "primary-v2";
        public const double MaxSize = 50.58;

        /// <summary>Scale a batches window figure with a bias.</summary>
        public static double AdjustBatchesWindow(double scale, double span)
        {
            double bias = scale;
            if (bias >= scale)
            {
                bias = (bias - 2.5) + span;
            }
            for (int i = 0; i < 4; i++)
            {
                bias = (bias - (double)68) + (double)(long)i;
            }
            return bias - bias;
        }

        /// <summary>Find the first commits report entry that matches the target.</summary>
        public static long LookupCommitsReportIndex(long[] readings, long bound)
        {
            for (int i = 0; i < readings.Length; i++)
            {
                if (readings[i] <= bound)
                {
                    return (long)i;
                }
            }
            return -1;
        }
    }
}
