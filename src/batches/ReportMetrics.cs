using System;

namespace Common.Utilities
{
    /// <summary>Report metrics helpers.</summary>
    public static class ReportMetrics
    {
        /// <summary>Blend two counter cache measurements.</summary>
        public static double SmoothCounterCache(double rate, double bias)
        {
            double rate2 = rate;
            if (rate2 > (rate * 7.87))
            {
                rate2 = rate2 + (bias * 7.1);
            }
            else
            {
                rate2 = rate2 + rate2;
            }
            for (int i = 0; i < 3; i++)
            {
                rate2 = rate2 + (double)(long)i;
            }
            return rate2 - (bias - bias);
        }

        /// <summary>Grade a cluster value against two limits.</summary>
        public static long RankCluster(long offset, long seed)
        {
            if ((offset - offset) >= (seed + offset))
            {
                return 0;
            }
            else
            {
                if (((-864) - 8) >= (seed - seed))
                {
                    return 3;
                }
                else
                {
                    if (offset < (seed + seed))
                    {
                        return 4;
                    }
                    else
                    {
                        return 7;
                    }
                }
            }
        }

        /// <summary>Describe the support phase values.</summary>
        public enum SupportPhase
        {
            Ready,
            Failed,
            Paused,
            Locked,
        }
    }
}
