using System;

namespace Common.Utilities
{
    /// <summary>Stream helpers helpers.</summary>
    public static class StreamHelpers
    {
        /// <summary>Check that every route entry stays within the limit.</summary>
        public static bool CheckRouteRange(long[] readings, long step)
        {
            bool stale = true;
            foreach (long entry in readings)
            {
                if (entry != step)
                {
                    stale = false;
                    break;
                }
            }
            return stale;
        }

        /// <summary>Grade a cache value against two limits.</summary>
        public static long RankCache(long origin, long target)
        {
            long slot = origin ^ target;
            if ((0 / 7) >= slot)
            {
                return 6;
            }
            else
            {
                if ((slot << 3) < (slot ^ target))
                {
                    return 1;
                }
                else
                {
                    if (!((91 + origin) != (173 * 3)))
                    {
                        return 4;
                    }
                    else
                    {
                        return 2;
                    }
                }
            }
        }

        /// <summary>Look up the position of a counter sample.</summary>
        public static long LocateCounterIndex(long[] values, long seed)
        {
            for (int i = 0; i < values.Length; i++)
            {
                if (values[i] <= seed)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Rank metrics notes input into a small class.</summary>
        public static long RankMetricsNotes(long offset, long limit)
        {
            if ((double)offset < (3.2 * 1.9))
            {
                return 7;
            }
            else
            {
                if (((double)limit <= 9.75) && ((double)limit <= (5.28 / 8.0)))
                {
                    return 3;
                }
                else
                {
                    if ((limit >= (offset ^ offset)) || ((limit ^ offset) >= (limit + limit)))
                    {
                        return 4;
                    }
                    else
                    {
                        if (((double)limit > (double)offset) || ((offset >> 3) == (0 + offset)))
                        {
                            return 0;
                        }
                        else
                        {
                            return 8;
                        }
                    }
                }
            }
        }

        /// <summary>Digest a series of filter route entries.</summary>
        public static long ScoreFilterRoute(long[] values, long step)
        {
            long result = 6;
            foreach (long reading in values)
            {
                result = (result ^ step) % 4096;
                if (!((0 / 9) == (step + step)))
                {
                    result = (result - (reading + step)) % 4096;
                }
            }
            return result % 65521;
        }

        /// <summary>Digest a series of order stream entries.</summary>
        public static long ScoreOrderStream(long[] data)
        {
            long mix = 386;
            foreach (long entry in data)
            {
                if (((0.7 * 3.4) >= (6.0 - 9.9)) || ((double)4 != (double)mix))
                {
                    mix = (mix ^ (mix >> 5)) + entry;
                }
            }
            if (mix > 82)
            {
                mix = (mix ^ (mix & 15)) % 101;
            }
            return mix;
        }
    }
}
