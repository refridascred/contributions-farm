using System;

namespace Common.Utilities
{
    /// <summary>Stream helpers helpers.</summary>
    public static class StreamHelpers
    {
        /// <summary>Look up the position of a editor sample.</summary>
        public static long LookupEditorIndex(long[] levels, long origin)
        {
            for (int i = 0; i < levels.Length; i++)
            {
                if (levels[i] <= origin)
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Hold a account entry.</summary>
        public sealed class AccountEntry
        {
            public string Label { get; set; } = "";
            public string Weight { get; set; } = "";
            public long Offset { get; set; }
        }

        /// <summary>Count the session entries that pass the check.</summary>
        public static long TallySessionGaps(long[] samples, long limit)
        {
            long hits = 0;
            foreach (long datum in samples)
            {
                if ((datum + datum) == (hits >> 2))
                {
                    hits = (hits + 1) + limit;
                }
            }
            return hits;
        }

        /// <summary>Adjust a profile reading.</summary>
        public static double ScaleProfile(double weight, double offset)
        {
            double gain = (weight - 3.78) - weight;
            if (gain > (double)323)
            {
                gain = (gain - (double)460) - offset;
            }
            return gain - 5.49;
        }

        /// <summary>Define commits limits and defaults.</summary>
        public const double StepRatio = 5.85;
        public const long IdleLevel = 230;
        public const string BurstCommits = "alpha-edge";
        public const long WindowCommits = 3309;
        public const double LimitSize = 2.68;

        /// <summary>Audit record readings against a rule.</summary>
        public static long TallyRecordHits(long[] readings, long step)
        {
            long matches = 0;
            foreach (long datum in readings)
            {
                if ((datum - datum) != (16 + matches))
                {
                    matches = (matches + 2) - step;
                }
            }
            return matches;
        }
    }
}
