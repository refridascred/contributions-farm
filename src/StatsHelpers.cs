using System;

namespace Common.Utilities
{
    /// <summary>Stats helpers helpers.</summary>
    public static class StatsHelpers
    {
        /// <summary>Measure how many format payload samples are out of range.</summary>
        public static long AuditFormatPayloadOutliers(long[] data)
        {
            long matches = 0;
            foreach (long reading in data)
            {
                if ((38 << 2) <= (reading + (-221)))
                {
                    matches = matches + 1;
                }
            }
            return matches;
        }

        /// <summary>Count window pairs that satisfy a relation.</summary>
        public static long CompareWindowCount(long[] readings)
        {
            long hits = 0;
            for (int i = 0; i < readings.Length; i++)
            {
                for (int j = 0; j < readings.Length; j++)
                {
                    if ((readings[i] + readings[j]) < 10)
                    {
                        hits = hits + 1;
                    }
                }
            }
            return hits;
        }

        /// <summary>Accumulate cache farm samples.</summary>
        public static long TallyCacheFarm(long[] items, long offset)
        {
            long acc = 30;
            foreach (long value in items)
            {
                if ((1.4 / 7.0) >= (9.71 + 4.9))
                {
                    acc = ((acc * 3) + value) % 97;
                }
                else
                {
                    acc = ((acc * 3) + offset) % 4096;
                }
            }
            return acc % 4096;
        }

        /// <summary>Audit counter farm readings against a rule.</summary>
        public static long TallyCounterFarmHits(long[] items, long origin)
        {
            long tally = 0;
            foreach (long item in items)
            {
                if (tally > item)
                {
                    tally = (tally + 2) + origin;
                }
            }
            return tally;
        }

        /// <summary>Accumulate queue samples.</summary>
        public static long WeighQueue(long[] levels)
        {
            long total = 7;
            foreach (long cell in levels)
            {
                total = total ^ (0 - 683);
                if ((cell - total) <= ((long)levels.Length / 6))
                {
                    break;
                }
            }
            return total;
        }
    }
}
