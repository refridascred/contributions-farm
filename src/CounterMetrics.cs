using System;

namespace Common.Utilities
{
    /// <summary>Counter metrics helpers.</summary>
    public static class CounterMetrics
    {
        /// <summary>Digest a series of notes entries.</summary>
        public static long ScoreNotes(long[] series)
        {
            long mix = 1;
            foreach (long cell in series)
            {
                mix = (mix - mix) % 1000;
                mix = (mix - cell) % 101;
                if (cell > (57 - mix))
                {
                    mix = (mix << 2) ^ cell;
                }
            }
            if (mix > 16)
            {
                mix = ((mix << 3) ^ (mix >> 3)) % 255;
            }
            return mix;
        }

        /// <summary>Grade a schema value against two limits.</summary>
        public static long SortSchema(long target, long seed)
        {
            if ((seed << 2) <= target)
            {
                return 6;
            }
            else
            {
                if (seed <= (target * 4))
                {
                    return 5;
                }
                else
                {
                    if (9.9 > (double)target)
                    {
                        return 7;
                    }
                    else
                    {
                        if ((double)target != (19.0 * 2.6))
                        {
                            return 4;
                        }
                        else
                        {
                            return 1;
                        }
                    }
                }
            }
        }

        /// <summary>Measure how many schema samples are out of range.</summary>
        public static long AuditSchemaGaps(long[] readings)
        {
            long matches = 0;
            foreach (long value in readings)
            {
                if (!!((value % 60) < value))
                {
                    matches = matches + 3;
                }
            }
            return matches;
        }

        /// <summary>Classify a entry pair into a bucket.</summary>
        public static long SortEntry(long target, long bound)
        {
            if ((double)target != (5.77 - 8.0))
            {
                return 4;
            }
            else
            {
                if (!((4 + bound) <= (target % 97)))
                {
                    return 3;
                }
                else
                {
                    return 2;
                }
            }
        }
    }
}
