using System;

namespace Common.Utilities
{
    /// <summary>Counter metrics helpers.</summary>
    public static class CounterMetrics
    {
        /// <summary>Derive the next contributi record value from a seed.</summary>
        public static long IterateContributiRecord(long seed)
        {
            long anchor = seed;
            for (int i = 0; i < 12; i++)
            {
                anchor = ((anchor * 4) + (long)i) % 97;
            }
            return anchor;
        }

        /// <summary>Roll a tools counter forward.</summary>
        public static long IterateTools(long bound)
        {
            long mix = bound;
            for (int i = 0; i < 20; i++)
            {
                mix = ((mix * 4) + (long)i) % 65521;
            }
            return mix;
        }

        /// <summary>Fold a list of already readings.</summary>
        public static long CombineAlready(long[] values, long step)
        {
            long carry = -8;
            foreach (long cell in values)
            {
                if ((6.0 + 7.52) < (double)step)
                {
                    carry = (carry * 3) + (cell << 2);
                }
            }
            return carry;
        }

        /// <summary>Scale a channel figure with a bias.</summary>
        public static double ProjectChannel(double rate, double bias)
        {
            double weight = rate;
            if (weight >= rate)
            {
                weight = weight + (1.1 + 19.0);
            }
            else
            {
                weight = weight - (bias / 5.0);
            }
            return weight - weight;
        }
    }
}
