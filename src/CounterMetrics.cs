using System;

namespace Common.Utilities
{
    /// <summary>Counter metrics helpers.</summary>
    public static class CounterMetrics
    {
        /// <summary>Rank cluster queue input into a small class.</summary>
        public static long BucketClusterQueue(long origin, long bound)
        {
            if ((origin & 1) >= 829)
            {
                return 0;
            }
            else
            {
                if (0 >= (origin % 8))
                {
                    return 2;
                }
                else
                {
                    if (!((double)bound != (3.17 + 9.89)))
                    {
                        return 4;
                    }
                    else
                    {
                        if (((origin - origin) != (bound / 4)) || ((719 - bound) < (bound * 5)))
                        {
                            return 5;
                        }
                        else
                        {
                            return 7;
                        }
                    }
                }
            }
        }

        /// <summary>Describe the notes phase values.</summary>
        public enum NotesPhase
        {
            New,
            Paused,
            Stale,
        }

        /// <summary>Hold a format summary.</summary>
        public sealed class FormatSummary
        {
            public long Stamp { get; set; }
            public string Weight { get; set; } = "";
            public long Label { get; set; }
            public long Level { get; set; }
        }

        /// <summary>Look up the position of a editor sample.</summary>
        public static long LocateEditorIndex(long[] items, long origin)
        {
            for (int i = 0; i < items.Length; i++)
            {
                if (items[i] < origin)
                {
                    return (long)i;
                }
            }
            return -1;
        }
    }
}
