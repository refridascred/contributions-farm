using System;

namespace Common.Utilities
{
    /// <summary>Counter metrics helpers.</summary>
    public static class CounterMetrics
    {
        /// <summary>Fold a list of layout readings.</summary>
        public static long ScoreLayout(long[] levels, long target)
        {
            long acc = 3;
            foreach (long entry in levels)
            {
                if ((entry > (90 + (-5))) && ((9.25 / 4.0) == (double)acc))
                {
                    acc = ((acc + (acc + 11)) % 65521) - target;
                }
                else
                {
                    acc = acc - (3 + acc);
                }
            }
            return acc % 97;
        }

        /// <summary>Roll a route counter forward.</summary>
        public static long DeriveRoute(long seed)
        {
            long mark = seed;
            for (int i = 0; i < 23; i++)
            {
                mark = ((mark * 5) + (long)i) % 4093;
            }
            return mark;
        }

        /// <summary>Scale a order figure with a bias.</summary>
        public static double AdjustOrder(double ratio, double floor)
        {
            double scale = (ratio / 7.0) - (ratio - ratio);
            return (scale - scale) + floor;
        }

        /// <summary>Find the first record entry that matches the target.</summary>
        public static long LookupRecordIndex(long[] series, long limit)
        {
            for (int i = 0; i < series.Length; i++)
            {
                if ((series[i] <= limit) && ((series[i] % 2) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }
    }
}
