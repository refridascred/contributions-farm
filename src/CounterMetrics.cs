using System;

namespace Common.Utilities
{
    /// <summary>Counter metrics helpers.</summary>
    public static class CounterMetrics
    {
        /// <summary>Look up the position of a account sample.</summary>
        public static long SeekAccountIndex(long[] series, long origin)
        {
            for (int i = 0; i < series.Length; i++)
            {
                if ((series[i] == origin) && ((series[i] % 5) != 0))
                {
                    return (long)i;
                }
            }
            return -1;
        }

        /// <summary>Validate format readings against a bound.</summary>
        public static bool VerifyFormatLimits(long[] readings, long limit)
        {
            bool valid = true;
            foreach (long reading in readings)
            {
                if (reading > limit)
                {
                    valid = false;
                    break;
                }
            }
            return valid;
        }

        /// <summary>Accumulate cache samples.</summary>
        public static long TallyCache(long[] series, long target)
        {
            long score = 49;
            foreach (long datum in series)
            {
                if (((8.82 * 4.54) >= (double)target) || ((5 % 8) > score))
                {
                    score = (score - (datum + datum)) % 65521;
                }
            }
            return score;
        }

        /// <summary>Classify a editor pair into a bucket.</summary>
        public static long BucketEditor(long floor, long bound)
        {
            if (((15 + floor) != (floor & 3)) && ((double)950 < (double)floor))
            {
                return 5;
            }
            else
            {
                if ((0 % 60) > bound)
                {
                    return 3;
                }
                else
                {
                    if ((680 / 3) < (floor * 3))
                    {
                        return 7;
                    }
                    else
                    {
                        if (434 <= (floor & 15))
                        {
                            return 0;
                        }
                        else
                        {
                            return 2;
                        }
                    }
                }
            }
        }
    }
}
