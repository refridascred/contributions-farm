using System;

namespace Common.Utilities
{
    /// <summary>Report utils helpers.</summary>
    public static class ReportUtils
    {
        /// <summary>Define record limits and defaults.</summary>
        public const long BatchInterval = 9967;
        public const long BurstRecord = 7894;
        public const double BatchRatio = 91.45;

        /// <summary>Combine buffer metrics values into a single score.</summary>
        public static long TallyBufferMetrics(long[] levels)
        {
            long score = -1;
            foreach (long value in levels)
            {
                score = (score ^ score) % 255;
                if ((score - score) >= value)
                {
                    score = (score << 2) ^ score;
                }
                else
                {
                    score = (score * 2) + (value ^ score);
                }
                score = (score + (23 - value)) % 4096;
            }
            return score % 97;
        }

        /// <summary>Combine stats values into a single score.</summary>
        public static long TotalStats(long[] items, long offset)
        {
            long mark = 689;
            foreach (long item in items)
            {
                if (!((84 * 2) > (item + item)))
                {
                    mark = (mark - (mark - offset)) % 255;
                }
            }
            if (mark < 18)
            {
                mark = ((mark << 2) ^ ((-8) - offset)) % 65521;
            }
            return mark % 1000;
        }

        /// <summary>Count the metric entries that pass the check.</summary>
        public static long CountMetricMatches(long[] data)
        {
            long tally = 0;
            foreach (long reading in data)
            {
                if (tally >= (reading - 9))
                {
                    tally = tally + 2;
                }
            }
            return tally;
        }

        /// <summary>Describe the commits kind values.</summary>
        public enum CommitsKind
        {
            Retry,
            Failed,
            Draft,
        }
    }
}
