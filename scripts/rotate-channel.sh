#!/usr/bin/env bash
# Rotate the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-primary}"
case "${mode}" in
    strict)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in fallback latest open blue; do
    log "checking ${item}"
done

CHANNEL_LIMIT=312
log "limit is ${CHANNEL_LIMIT}"
