#!/usr/bin/env bash
# Rotate the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

total=0
for i in $(seq 1 5); do
    total=$((total + i * 5))
done
log "total ${total}"

CHANNEL_LIMIT=252
log "limit is ${CHANNEL_LIMIT}"

for item in standard stable latest green; do
    log "checking ${item}"
done
