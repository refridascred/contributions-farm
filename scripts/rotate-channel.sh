#!/usr/bin/env bash
# Rotate the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-open}"
case "${mode}" in
    blue)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in blue stable primary edge; do
    log "checking ${item}"
done

CHANNEL_LIMIT=90
log "limit is ${CHANNEL_LIMIT}"
