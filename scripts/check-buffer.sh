#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-blue}"
case "${mode}" in
    eu-west)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in primary green standard local; do
    log "checking ${item}"
done

BUFFER_LIMIT=273
log "limit is ${BUFFER_LIMIT}"
