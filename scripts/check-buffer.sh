#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-cached}"
case "${mode}" in
    stable)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in strict standard staging legacy; do
    log "checking ${item}"
done

BUFFER_LIMIT=349
log "limit is ${BUFFER_LIMIT}"
