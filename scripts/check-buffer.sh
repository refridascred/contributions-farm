#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-staging}"
case "${mode}" in
    stable)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in local staging green; do
    log "checking ${item}"
done

BUFFER_LIMIT=495
log "limit is ${BUFFER_LIMIT}"
