#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-legacy}"
case "${mode}" in
    legacy)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in staging blue local open; do
    log "checking ${item}"
done

BUFFER_LIMIT=336
log "limit is ${BUFFER_LIMIT}"
