#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-fallback}"
case "${mode}" in
    latest)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in cached blue strict primary; do
    log "checking ${item}"
done

BUFFER_LIMIT=193
log "limit is ${BUFFER_LIMIT}"
