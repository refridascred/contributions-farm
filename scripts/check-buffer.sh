#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-standard}"
case "${mode}" in
    strict)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in standard latest blue; do
    log "checking ${item}"
done

BUFFER_LIMIT=297
log "limit is ${BUFFER_LIMIT}"
