#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    edge)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green open legacy; do
    log "checking ${item}"
done

BUFFER_LIMIT=26
log "limit is ${BUFFER_LIMIT}"
