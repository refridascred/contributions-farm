#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-green}"
case "${mode}" in
    blue)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in staging standard; do
    log "checking ${item}"
done

BUFFER_LIMIT=481
log "limit is ${BUFFER_LIMIT}"
