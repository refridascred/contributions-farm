#!/usr/bin/env bash
# Check the buffer data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    standard)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in latest strict staging primary; do
    log "checking ${item}"
done

BUFFER_LIMIT=418
log "limit is ${BUFFER_LIMIT}"
