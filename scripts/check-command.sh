#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-stable}"
case "${mode}" in
    open)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green standard staging primary; do
    log "checking ${item}"
done

COMMAND_LIMIT=125
log "limit is ${COMMAND_LIMIT}"
