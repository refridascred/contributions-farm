#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-green}"
case "${mode}" in
    local)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green legacy; do
    log "checking ${item}"
done

COMMAND_LIMIT=487
log "limit is ${COMMAND_LIMIT}"
