#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-eu-west}"
case "${mode}" in
    legacy)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in edge local standard; do
    log "checking ${item}"
done

COMMAND_LIMIT=425
log "limit is ${COMMAND_LIMIT}"
