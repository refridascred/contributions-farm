#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-green}"
case "${mode}" in
    cached)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green local; do
    log "checking ${item}"
done

COMMAND_LIMIT=336
log "limit is ${COMMAND_LIMIT}"
