#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-staging}"
case "${mode}" in
    eu-west)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in standard local latest stable; do
    log "checking ${item}"
done

COMMAND_LIMIT=224
log "limit is ${COMMAND_LIMIT}"
