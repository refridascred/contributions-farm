#!/usr/bin/env bash
# Check the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-staging}"
case "${mode}" in
    stable)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green standard open; do
    log "checking ${item}"
done

COMMAND_LIMIT=436
log "limit is ${COMMAND_LIMIT}"
