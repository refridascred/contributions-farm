#!/usr/bin/env bash
# Report the record data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    staging)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in staging edge open cached; do
    log "checking ${item}"
done

RECORD_LIMIT=201
log "limit is ${RECORD_LIMIT}"
