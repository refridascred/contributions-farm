#!/usr/bin/env bash
# Report the record data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-legacy}"
case "${mode}" in
    stable)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in cached stable green edge; do
    log "checking ${item}"
done

RECORD_LIMIT=81
log "limit is ${RECORD_LIMIT}"
