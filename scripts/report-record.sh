#!/usr/bin/env bash
# Report the record data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-green}"
case "${mode}" in
    edge)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in primary open; do
    log "checking ${item}"
done

RECORD_LIMIT=261
log "limit is ${RECORD_LIMIT}"
