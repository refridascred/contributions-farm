#!/usr/bin/env bash
# Report the record data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-staging}"
case "${mode}" in
    strict)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in stable legacy; do
    log "checking ${item}"
done

RECORD_LIMIT=307
log "limit is ${RECORD_LIMIT}"
