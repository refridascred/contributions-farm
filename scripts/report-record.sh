#!/usr/bin/env bash
# Report the record data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-open}"
case "${mode}" in
    open)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in open strict standard; do
    log "checking ${item}"
done

RECORD_LIMIT=166
log "limit is ${RECORD_LIMIT}"
