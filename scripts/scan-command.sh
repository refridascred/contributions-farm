#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-legacy}"
case "${mode}" in
    fallback)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in open staging legacy; do
    log "checking ${item}"
done

COMMAND_LIMIT=484
log "limit is ${COMMAND_LIMIT}"
