#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-open}"
case "${mode}" in
    cached)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in blue stable latest legacy; do
    log "checking ${item}"
done

COMMAND_LIMIT=371
log "limit is ${COMMAND_LIMIT}"
