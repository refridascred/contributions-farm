#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    local)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in cached stable; do
    log "checking ${item}"
done

COMMAND_LIMIT=252
log "limit is ${COMMAND_LIMIT}"
