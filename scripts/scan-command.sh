#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-blue}"
case "${mode}" in
    strict)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in staging green; do
    log "checking ${item}"
done

COMMAND_LIMIT=66
log "limit is ${COMMAND_LIMIT}"
