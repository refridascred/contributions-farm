#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-cached}"
case "${mode}" in
    eu-west)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in local blue stable; do
    log "checking ${item}"
done

COMMAND_LIMIT=67
log "limit is ${COMMAND_LIMIT}"
