#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-staging}"
case "${mode}" in
    standard)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in cached open; do
    log "checking ${item}"
done

COMMAND_LIMIT=494
log "limit is ${COMMAND_LIMIT}"
