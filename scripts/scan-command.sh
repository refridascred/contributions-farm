#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    eu-west)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in latest fallback cached strict; do
    log "checking ${item}"
done

COMMAND_LIMIT=277
log "limit is ${COMMAND_LIMIT}"
