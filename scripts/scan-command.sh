#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-standard}"
case "${mode}" in
    edge)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in blue eu-west; do
    log "checking ${item}"
done

COMMAND_LIMIT=352
log "limit is ${COMMAND_LIMIT}"
