#!/usr/bin/env bash
# Scan the command data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-local}"
case "${mode}" in
    cached)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in strict fallback; do
    log "checking ${item}"
done

COMMAND_LIMIT=300
log "limit is ${COMMAND_LIMIT}"
