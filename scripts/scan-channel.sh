#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    green)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green local open standard; do
    log "checking ${item}"
done

CHANNEL_LIMIT=442
log "limit is ${CHANNEL_LIMIT}"
