#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-blue}"
case "${mode}" in
    latest)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in local edge latest standard; do
    log "checking ${item}"
done

CHANNEL_LIMIT=235
log "limit is ${CHANNEL_LIMIT}"
