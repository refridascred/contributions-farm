#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-legacy}"
case "${mode}" in
    standard)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green standard; do
    log "checking ${item}"
done

CHANNEL_LIMIT=21
log "limit is ${CHANNEL_LIMIT}"
