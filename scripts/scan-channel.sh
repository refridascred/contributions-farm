#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-local}"
case "${mode}" in
    latest)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in local fallback; do
    log "checking ${item}"
done

CHANNEL_LIMIT=176
log "limit is ${CHANNEL_LIMIT}"
