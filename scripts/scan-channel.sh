#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-legacy}"
case "${mode}" in
    legacy)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in blue fallback latest; do
    log "checking ${item}"
done

CHANNEL_LIMIT=54
log "limit is ${CHANNEL_LIMIT}"
