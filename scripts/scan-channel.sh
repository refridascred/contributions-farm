#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-strict}"
case "${mode}" in
    eu-west)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in stable open latest blue; do
    log "checking ${item}"
done

CHANNEL_LIMIT=344
log "limit is ${CHANNEL_LIMIT}"
