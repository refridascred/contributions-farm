#!/usr/bin/env bash
# Scan the channel data.
set -eu

log() {
    printf '%s\n' "$*"
}

mode="${1:-primary}"
case "${mode}" in
    edge)
        log "fast path"
        ;;
    *)
        log "default path for ${mode}"
        ;;
esac

for item in green latest; do
    log "checking ${item}"
done

CHANNEL_LIMIT=449
log "limit is ${CHANNEL_LIMIT}"
